"""Run the example flows headless and keep what they measured: ``results/<flow>/summary.json`` (every node's status,
summary, metrics and timings on this machine) and small thumbnails of the figures; ``results/RESULTS.md`` is the
table of all of them.

    python examples/flow_studio/run_examples.py                 # every example
    python examples/flow_studio/run_examples.py heat_1d poisson_2d
    python examples/flow_studio/run_examples.py --cached          # reuse cached node outputs (timings are then 0)

Without ``--cached`` every node is recomputed, so the wall times are what the flows cost on this machine.
"""
from __future__ import annotations

import json
import platform
import sys
import time
from pathlib import Path

import pinneapple_flow as pf
from pinneapple_flow.service import FLOWS_DIR

HERE = Path(__file__).parent
RESULTS = HERE / "results"
WORK = HERE / "_runs"


def thumbnail(src: str, dst: Path, width: int = 640) -> None:
    from PIL import Image
    im = Image.open(src)
    if getattr(im, "n_frames", 1) > 1:                     # a GIF: keep its first frame
        im.seek(0)
    im = im.convert("RGB")
    if im.width > width:
        im = im.resize((width, int(im.height * width / im.width)), Image.LANCZOS)
    im.save(dst, optimize=True)


def run_one(name: str, cache: bool = False) -> dict:
    flow = pf.Flow.load(FLOWS_DIR / f"{name}.json")
    t0 = time.time()
    res = pf.run(flow, workdir=WORK, cache=cache)
    out = RESULTS / name
    out.mkdir(parents=True, exist_ok=True)
    for old in [*out.glob("*.png"), *out.glob("*.mp4")]:
        old.unlink()
    nodes = {}
    for nid, s in res.nodes.items():
        rep = s["report"]
        figs = []
        for i, f in enumerate(rep.get("figures") or []):
            dst = out / f"{nid}_{f['name']}.png"
            try:
                thumbnail(f["path"], dst)
                figs.append(dst.name)
            except OSError:
                pass
            del i
        vid = (rep.get("views") or {}).get("video")
        if vid and Path(vid["path"]).is_file():             # a rendered clip (small mp4) is kept with the results
            import shutil
            shutil.copy(vid["path"], out / f"{nid}_clip.mp4")
            figs.append(f"{nid}_clip.mp4")
        nodes[nid] = {"type": flow.node(nid).type, "status": s["status"], "seconds": s["seconds"],
                      "error": s["error"], "summary": rep.get("summary"), "metrics": rep.get("metrics"),
                      "warnings": rep.get("warnings"), "tables": rep.get("tables"), "figures": figs}
    summary = {"flow": name, "title": flow.name, "status": res.status, "wall_seconds": round(time.time() - t0, 1),
               "machine": f"{platform.machine()} {platform.processor() or ''} ({sys.platform}), CPU only",
               "date": time.strftime("%Y-%m-%d"), "meta": flow.meta, "nodes": nodes,
               "cached_nodes": sorted(k for k, n in nodes.items() if n["status"] == "cached")}
    (out / "summary.json").write_text(json.dumps(summary, indent=1, default=str))
    print(f"{name}: {res.status} in {summary['wall_seconds']} s")
    for nid, n in nodes.items():
        print(f"  {nid:<14} {n['status']:<9} {n['summary'] or n['error'] or ''}"[:200])
    return summary


def table() -> None:
    rows = ["| flow | status | wall time | key measured results |", "|---|---|---|---|"]
    for p in sorted(RESULTS.glob("*/summary.json")):
        s = json.loads(p.read_text())
        key = []
        for nid, n in s["nodes"].items():
            if n["summary"] and n["type"] in ("validate.compare", "validate.lab", "inverse.discover", "inverse.calibrate",
                                              "surrogate.train", "surrogate.hpo", "twin.connect", "forecast.lab",
                                              "uq.sensitivity", "flight.takeoff", "problem.generic", "forecast.enso",
                                              "twin.auto", "vehicle.simulate", "terramechanics.zoo_surrogate",
                                              "vehicle.dashboard"):
                key.append(f"{nid}: {n['summary']}")
            elif n["status"] == "failed":
                key.append(f"{nid}: FAILED ({(n['error'] or '')[:120]})")
        wall = f"{s['wall_seconds']} s" + (" (cached nodes)" if s.get("cached_nodes") else "")
        rows.append(f"| [{s['title']}]({p.parent.name}/summary.json) | {s['status']} | {wall} | "
                    + "<br>".join(k.replace("|", "/") for k in key) + " |")
    (RESULTS / "RESULTS.md").write_text("# Example flows: measured results\n\nGenerated by `run_examples.py` on a "
                                        "CPU-only machine; every number below was measured by the flow's own nodes "
                                        "(see each `summary.json` for all metrics and how they were measured).\n\n"
                                        + "\n".join(rows) + "\n")


if __name__ == "__main__":
    import os
    import shutil
    # a Lab of its own, emptied at the start: an item's letter then comes from this run of the examples, never from
    # runs recorded by older code
    os.environ.setdefault("PINNEAPPLE_FLOW_HOME", str(WORK / "home"))
    shutil.rmtree(Path(os.environ["PINNEAPPLE_FLOW_HOME"]) / "lab", ignore_errors=True)
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    names = args or [p.stem for p in sorted(FLOWS_DIR.glob("*.json"))]
    for nm in names:
        run_one(nm, cache="--cached" in sys.argv)
    table()
