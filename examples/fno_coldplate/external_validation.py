"""Independent evaluation controls for the existing FNO cold-plate case.

This script runs the PINNeAPPle finite-volume reference solver and the very same
physics checks used by the model and CLI. Its controls are *not* evidence that
a learned surrogate is validated: an exact FV reference must pass, an altered
field must fail, and a physically valid but out-of-envelope query must be rejected.
Run from the repository root:
    python examples/fno_coldplate/external_validation.py --out /tmp/coldplate-audit
    python examples/fno_coldplate/external_validation.py --fno-smoke --out /tmp/coldplate-audit
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import platform
import subprocess
import sys
from pathlib import Path

import numpy as np
import scipy

from pinneapple_physics import darcy_checks as dc
from pinneapple_simulation.numerical_solvers import operator_benchmarks as ob


def _git_sha() -> str | None:
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"], text=True, stderr=subprocess.DEVNULL
        ).strip()
    except (OSError, subprocess.CalledProcessError):
        return None


def _assess(a: np.ndarray, u: np.ndarray, f: float, envelope=None) -> dict:
    checks = dc.sample_checks(a, u, f, envelope=envelope)
    return {
        "verdict": dc.sample_verdict(checks),
        "checks": checks,
        "failed": [item["key"] for item in checks if not item["passed"]],
    }


def run_controls(out: str | Path, n: int = 32, source_levels=(0.5, 1.0, 2.0)) -> dict:
    """Run physics-positive, corrupted-field, and OOD controls for each source.

    Parameters and tolerances are set before observing the results. Every reference
    is generated by PINNeAPPle's finite-volume solver, not an ML prediction.
    """
    if n < 32:
        raise ValueError("n must be >=32 so the boundary extrapolation meets the documented check")
    output = Path(out)
    output.mkdir(parents=True, exist_ok=True)

    # Training envelope deliberately contains homogeneous positive coefficients
    # between 3 and 12. A perfectly solved a=24 case is OOD by design.
    training = np.stack([np.full((n, n), k) for k in (3.0, 6.0, 12.0)])
    envelope = dc.CoefficientEnvelope.fit(training, q=0.0)
    a_id = np.full((n, n), 6.0)
    a_ood = np.full((n, n), 24.0)
    cases = []
    for source in source_levels:
        source = float(source)
        if source <= 0:
            raise ValueError("source must be positive")
        u = ob.darcy_2d(a_id, source)
        corrupted = u * 0.5
        u_ood = ob.darcy_2d(a_ood, source)

        clean = _assess(a_id, u, source, envelope)
        broken = _assess(a_id, corrupted, source, envelope)
        ood = _assess(a_ood, u_ood, source, envelope)
        physics_ood = _assess(a_ood, u_ood, source)
        passed = (
            clean["verdict"] == "PASS"
            and broken["verdict"] == "FAIL"
            and ood["verdict"] == "FAIL"
            and physics_ood["verdict"] == "PASS"
            and "a_max" in ood["failed"]
        )
        label = str(source).replace(".", "p")
        dc.save_darcy_npz(output / f"clean_f{label}.npz", a_id, u)
        dc.save_darcy_npz(output / f"corrupted_f{label}.npz", a_id, corrupted)
        dc.save_darcy_npz(output / f"ood_f{label}.npz", a_ood, u_ood)
        cases.append({
            "forcing": source,
            "clean_fv_reference": clean,
            "corrupted_half_amplitude": broken,
            "ood_fv_reference": ood,
            "ood_physics_only": physics_ood,
            "controls_passed": bool(passed),
            "corruption_relative_l2": float(np.linalg.norm(corrupted-u)/np.linalg.norm(u)),
        })

    artifact_sha256 = {
        file.name: hashlib.sha256(file.read_bytes()).hexdigest()
        for file in sorted(output.glob("*.npz"))
    }
    report = {
        "schema": "pinneapple.external-validation/1",
        "experiment": "fno_coldplate/negative_controls",
        "status": "PASS" if all(x["controls_passed"] for x in cases) else "FAIL",
        "scope": "finite-volume reference and PINNeAPPle physical checks; no ML training",
        "n": n,
        "source_levels": [float(x) for x in source_levels],
        "train_coefficients": [3.0, 6.0, 12.0],
        "in_distribution_coefficient": 6.0,
        "ood_coefficient": 24.0,
        "envelope": envelope.to_dict(),
        "provenance": {
            "git_commit": _git_sha(),
            "python": sys.version.split()[0],
            "platform": platform.platform(),
            "numpy": np.__version__,
            "scipy": scipy.__version__,
            "artifact_sha256": artifact_sha256,
        },
        "cases": cases,
    }
    (output / "controls.json").write_text(json.dumps(report, indent=2, allow_nan=False) + "\n")
    return report


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default="artifacts/external_validation/coldplate")
    parser.add_argument("--grid", type=int, default=32)
    parser.add_argument("--fno-smoke", action="store_true",
                        help="Also train the existing small FNO; smoke only, not a scientific benchmark")
    args = parser.parse_args()
    report = run_controls(args.out, n=args.grid)
    print(json.dumps({"controls": report["status"], "cases": len(report["cases"]),
                      "output": str(args.out)}, indent=2))
    if report["status"] != "PASS":
        return 1
    if args.fno_smoke:
        # Use the original PINNeAPPle model, training and trust checks without
        # duplicating any model code. Artifacts remain separate from controls.
        sys.path.insert(0, str(Path(__file__).resolve().parent))
        from run import main as run_fno
        summary = run_fno(smoke=True, base=str(Path(args.out) / "model_smoke"))
        (Path(args.out) / "fno_smoke.json").write_text(
            json.dumps({"qualification": "SMOKE ONLY — 6 steps, not a scientific result",
                        "model": summary}, indent=2, default=float) + "\n"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
