"""Regenerate docs/guides/fmi_compatibility.md: the FMI import compatibility of PINNeAPPle.

Downloads the Modelica Reference-FMUs release (checked against its SHA-256), builds a pythonfmu FMU, runs every FMU
through ``simulate_fmu`` in each interface it offers (``check_fmus``) and writes the tables.

    python examples/modelica/fmi_compatibility.py            # needs fmpy and pythonfmu (pip install fmpy pythonfmu)
"""
from __future__ import annotations

import hashlib
import io
import platform
import sys
import tempfile
import textwrap
import urllib.request
import zipfile
from datetime import date
from pathlib import Path

import fmpy
import pythonfmu

from pinneapple_simulation.external_solvers.modelica.fmi_compat import (
    check_fmus,
    markdown_table,
    platform_tag,
)

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "guides" / "fmi_compatibility.md"
REF_VERSION = "0.0.39"
REF_URL = f"https://github.com/modelica/Reference-FMUs/releases/download/v{REF_VERSION}/Reference-FMUs-{REF_VERSION}.zip"
REF_SHA256 = "6863d55e5818e1ca4e4614c4d4ba4047a921b4495f6336e7002874ed791f6c2a"

OSCILLATOR = '''
from pythonfmu import Fmi2Causality, Fmi2Variability, Fmi2Slave, Real


class Oscillator(Fmi2Slave):
    """x'' + 2 zeta w x' + w^2 x = 0."""

    def __init__(self, **kwargs):
        super().__init__(**kwargs)
        self.w, self.zeta, self.x, self.v = 2.0, 0.1, 1.0, 0.0
        self.register_variable(Real("w", causality=Fmi2Causality.parameter, variability=Fmi2Variability.tunable))
        self.register_variable(Real("zeta", causality=Fmi2Causality.parameter, variability=Fmi2Variability.tunable))
        self.register_variable(Real("x", causality=Fmi2Causality.output))
        self.register_variable(Real("v", causality=Fmi2Causality.output))

    def do_step(self, t, dt):
        a = -2 * self.zeta * self.w * self.v - self.w ** 2 * self.x
        self.x, self.v = self.x + dt * self.v, self.v + dt * a
        return True
'''


def reference_fmus(work: Path) -> list:
    data = urllib.request.urlopen(REF_URL, timeout=120).read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != REF_SHA256:
        sys.exit(f"Reference-FMUs {REF_VERSION}: SHA-256 {digest} does not match {REF_SHA256}")
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        z.extractall(work, members=[m for m in z.namelist() if m.endswith(".fmu")])
    return [sorted((work / d).glob("*.fmu")) for d in ("1.0/cs", "1.0/me", "2.0", "3.0")]


def pythonfmu_fmu(work: Path) -> Path:
    from pythonfmu.builder import FmuBuilder

    script = work / "Oscillator.py"
    script.write_text(textwrap.dedent(OSCILLATOR))
    return Path(FmuBuilder.build_FMU(script, dest=work))


def main() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        rows = []
        for group in reference_fmus(work):
            rows += check_fmus(group, exporter=f"Reference-FMUs {REF_VERSION}")
        rows += check_fmus([pythonfmu_fmu(work)], exporter=f"pythonfmu {pythonfmu.__version__}")
    passed = sum(r.passed for r in rows)
    notes = [f"- FMI {r.fmi_version} {r.fmu} ({r.interface}): {r.detail}" for r in rows if r.detail]
    OUT.write_text("\n".join([
        "# FMI import compatibility",
        "",
        "PINNeAPPle imports FMUs to generate training and validation data for Physics AI models "
        "(`pinneapple_simulation.external_solvers.modelica`: `simulate_fmu`, `fmu_to_upd`, sweeps). "
        "This page lists the FMUs that import has been tested with. It is generated by "
        "[`examples/modelica/fmi_compatibility.py`](https://github.com/PINNeAPPle-Labs/PINNeAPPle/blob/main/"
        "examples/modelica/fmi_compatibility.py), which runs every FMU through `simulate_fmu` in each interface it "
        "offers (`check_fmus` in `fmi_compat.py`).",
        "",
        "## Importing tool",
        "",
        f"- PINNeAPPle with fmpy {fmpy.__version__}, Python {platform.python_version()}, platform "
        f"{platform_tag()}, run on {date.today().isoformat()}.",
        "- CS = Co-Simulation, ME = Model Exchange.",
        "- A run passes when it reaches the stop time of the FMU's default experiment with finite outputs. For "
        "`Dahlquist` (x' = -k x) the trajectory is also compared with exp(-k t): within 1e-3 through Model "
        "Exchange and within 0.1 through Co-Simulation, where the FMU integrates with its own fixed-step explicit "
        "Euler.",
        f"- Result: {passed} of {len(rows)} runs passed.",
        "",
        "## Exporting tools",
        "",
        markdown_table(rows),
        "Measured errors:",
        "",
        *notes,
        "",
        "Not tested: `Clocks` (FMI 3.0, Scheduled Execution only), and the Windows and macOS binaries.",
        "",
    ]))
    print(f"{passed}/{len(rows)} passed -> {OUT}")


if __name__ == "__main__":
    main()
