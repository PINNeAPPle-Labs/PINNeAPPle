"""``python -m pinneapple_analysis.validation.fault_injection``: regenerate the detection matrix (check power).

Writes ``check_power.md`` (the Markdown tables) and ``check_power.json`` per problem into ``--out``, prints the
acceptance verdict and exits 1 when a fault is not caught at its documented magnitude or a check exceeds 1 % false
alarms. ``--small`` is the CI size (a few cases, seconds per problem).
"""
from __future__ import annotations

import argparse
import sys
import time
import warnings
from pathlib import Path

from .matrix import run_fault_injection

SIZES = {"small": {"n_cases": 6, "n_datasets": 3, "dataset_size": (6, 3)},
         "full": {"n_cases": 200, "n_datasets": 40, "dataset_size": (16, 8)}}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m pinneapple_analysis.validation.fault_injection",
                                 description="Detection matrix of the validation checks against the fault library.")
    ap.add_argument("--problems", default="darcy_2d,burgers_1d", help="comma-separated problems")
    ap.add_argument("--small", action="store_true", help="CI size")
    ap.add_argument("--n-cases", type=int, help="clean cases per problem (overrides the size)")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out", help="folder for check_power.md and check_power.json (default: print only)")
    a = ap.parse_args(argv)
    size = dict(SIZES["small" if a.small else "full"])
    if a.n_cases:
        size["n_cases"] = a.n_cases
    md, failures = [], []
    for name in [p.strip() for p in a.problems.split(",") if p.strip()]:
        t0 = time.time()
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", RuntimeWarning)
            rep = run_fault_injection(name, seed=a.seed, **size)
        md.append(rep.to_markdown())
        failures += [f"{name}: {f}" for f in rep.failures()]
        print(f"{name}: {len(rep.failures())} failure(s) in {time.time() - t0:.0f} s", file=sys.stderr)
        if a.out:
            rep.save(Path(a.out) / f"check_power_{name}.json")
    text = ("# Check power: the detection matrix\n\nGenerated by `python scripts/fault_injection_matrix.py` "
            f"(`{'--small' if a.small else 'full size'}`, seed {a.seed}); do not edit by hand. The method is "
            "described in [Check power](check_power.md).\n\n" + "\n\n".join(md))
    if a.out:
        Path(a.out).mkdir(parents=True, exist_ok=True)
        (Path(a.out) / "check_power_matrix.md").write_text(text, encoding="utf-8")
    else:
        print(text)
    for f in failures:
        print("FAIL:", f, file=sys.stderr)
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
