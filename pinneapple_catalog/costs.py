def _heat_spec(name: str):
    """A minimal 2-D heat case: the cheapest ProblemSpec a spec-driven solver can be handed, so the probe times the
    discretisation and not the case the user would have written."""
    from pinneapple_physics.pde_environment.spec import PDETermSpec, ProblemSpec
    return ProblemSpec(name=name, dim=2, coords=("x", "y"), fields=("u",),
                       pde=PDETermSpec(kind="heat", fields=("u",), coords=("x", "y"), params={"alpha": 0.01}),
                       domain_bounds={"x": (0.0, 1.0), "y": (0.0, 1.0)})


def _poisson_spec(name: str):
    from pinneapple_physics.pde_environment.spec import PDETermSpec, ProblemSpec
    return ProblemSpec(name=name, dim=2, coords=("x", "y"), fields=("u",),
                       pde=PDETermSpec(kind="poisson", fields=("u",), coords=("x", "y"), params={"source": 1.0}),
                       domain_bounds={"x": (0.0, 1.0), "y": (0.0, 1.0)})


