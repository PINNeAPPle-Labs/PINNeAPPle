@_probe("S1", "pinneapple_simulation.numerical_solvers.fdm.FDMSolver.forward (the direct 2-D Poisson path: 50 "
        "red-black SOR sweeps on an n x n grid)",
        "n (grid points per side)", [64, 128, 256, 512], declared="n^2")
def _probe_s1(n):
    import torch

    from pinneapple_simulation.numerical_solvers.fdm import FDMSolver
    # tol=0 pins the sweep count, so the fit measures the cost of a sweep on n^2 points and not the number of
    # sweeps a particular right-hand side happened to need to converge.
    solver = FDMSolver(nx=n, ny=n, iters=50, tol=0.0)
    f = torch.randn(n, n, dtype=torch.float64)
    bc = torch.zeros(n, n, dtype=torch.float64)
    return lambda: solver.forward(f, bc, dx=1.0 / n, dy=1.0 / n)


def _heat_spec(name: str):
    """A minimal 2-D heat case: the cheapest ProblemSpec a spec-driven solver can be handed, so the probe times the
    discretisation and not the case the user would have written."""
    from pinneapple_physics.pde_environment.spec import PDETermSpec, ProblemSpec
    return ProblemSpec(name=name, dim=2, coords=("x", "y"), fields=("u",),
                       pde=PDETermSpec(kind="heat", fields=("u",), coords=("x", "y"), params={"alpha": 0.01}),
                       domain_bounds={"x": (0.0, 1.0), "y": (0.0, 1.0)})


def _poisson_spec(name: str):
    from pinneapple_physics.pde_environment.spec import PDETermSpec, ProblemSpec
    return ProblemSpec(name=name, dim=2, coords=("x", "y"), fields=("u",),
                       pde=PDETermSpec(kind="poisson", fields=("u",), coords=("x", "y"), params={"source": 1.0}),
                       domain_bounds={"x": (0.0, 1.0), "y": (0.0, 1.0)})


@_probe("S3", "pinneapple_simulation.numerical_solvers.fvm.FVMSolver.forward (explicit Euler, 20 steps of a 2-D "
        "heat case)", "n (cells per side)", [64, 128, 256, 512], declared="n^2")
def _probe_s3(n):
    from pinneapple_simulation.numerical_solvers.fvm import FVMSolver
    solver = FVMSolver(nx=n, ny=n, nt=20, dt=1e-3)   # dt fixed: the CFL default would make nt grow with n
