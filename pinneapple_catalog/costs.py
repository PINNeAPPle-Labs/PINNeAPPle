@_probe("T1", "pinneapple_neural.trainer.trainer.Trainer.fit (one epoch of a 8-16-1 tanh MLP on CPU, batch 64)",
        "n (training samples in the epoch)", [2048, 8192, 32768], declared="n", repeats=3)
def _probe_t1(n):
    import tempfile

    import torch
    import torch.nn as nn
    from torch.utils.data import DataLoader, TensorDataset

    from pinneapple_neural.trainer.trainer import TrainConfig, Trainer

    class Mlp(nn.Module):
        def __init__(self):
            super().__init__()
            self.net = nn.Sequential(nn.Linear(8, 16), nn.Tanh(), nn.Linear(16, 1))

        def forward(self, x):
            return self.net(x)

    def loss_fn(model, y_hat, batch):
        return nn.functional.mse_loss(y_hat, batch["y"])

    loader = DataLoader(TensorDataset(torch.randn(n, 8), torch.randn(n, 1)), batch_size=64, shuffle=False)
    log_dir = tempfile.mkdtemp(prefix="cost-t1-")     # the trainer always opens a run log; keep it out of the repo
    trainer = Trainer(Mlp(), loss_fn=loss_fn)
    cfg = TrainConfig(epochs=1, lr=1e-3, device="cpu", log_dir=log_dir, run_name="cost-probe", save_best=False)
    return lambda: trainer.fit(loader, cfg=cfg)


