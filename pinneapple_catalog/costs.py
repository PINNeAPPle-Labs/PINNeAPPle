# --------------------------------------------------------------------------- the machine
def _cpu_name() -> str:
    """The CPU by name. ``platform.processor()`` answers ``"arm"`` on macOS and often ``""`` on Linux, which does
    not identify the machine a wall time came from, so the brand string is read from the OS when it has one."""
    if platform.system() == "Darwin":
        try:
            out = subprocess.run(["sysctl", "-n", "machdep.cpu.brand_string"], capture_output=True, text=True,
                                 timeout=5).stdout.strip()
            if out:
                return out
        except Exception:
            pass
    try:
        with open("/proc/cpuinfo", encoding="utf-8") as f:
            for line in f:
                if line.lower().startswith("model name"):
                    return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return platform.processor() or platform.machine()


def machine() -> dict[str, Any]:
    """What has to travel with a wall time for it to mean anything: the CPU, the cores, the platform, the versions."""
    info: dict[str, Any] = {
        "platform": platform.platform(),
        "system": platform.system(),
        "release": platform.release(),
        "machine": platform.machine(),
        "processor": platform.processor(),
        "cpu": _cpu_name(),
        "cpu_count": os.cpu_count(),
        "python": platform.python_version(),
    }
    try:
        import torch
        info["torch"] = torch.__version__
        info["cuda"] = torch.cuda.is_available()
    except Exception:  # torch absent: the numpy-only part of the library still measures
        info["torch"] = None
        info["cuda"] = False
    try:
        import psutil
        info["memory_bytes"] = int(psutil.virtual_memory().total)
    except Exception:
        info["memory_bytes"] = None
    return info


def _git_commit() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=HERE, capture_output=True, text=True,
                              timeout=10).stdout.strip()
    except Exception:
        return ""


# --------------------------------------------------------------------------- the probes
@dataclass(frozen=True)
class Probe:
    """One method's measuring stick.

    ``build(n)`` returns the callable that does the work at problem size ``n`` (its setup is not timed, as in
    :func:`pinneapple_analysis.cost.scaling_study`); ``declared`` is the complexity the code claims, so the fitted
    exponent has something to be checked against; ``what`` and ``size_axis`` say exactly what was run.

    ``flops=False`` says the FLOP counter cannot be run on this method in a time that leaves a usable measurement --
    it hooks every operator, and an assembly that issues thousands of small ones pays more for the hooks than for the
    work. The record then carries ``flops: null`` with an empty source, which is the honest answer and not a gap.
    """
    method_id: str
    what: str
    size_axis: str
    sizes: Sequence[int]
    build: Callable[[int], Callable[[], Any]]
    declared: str | None = None
    repeats: int = 5
    flops: bool = True


def _probe(method_id, what, size_axis, sizes, declared=None, repeats=5, flops=True):
    def deco(build):
        return Probe(method_id, what, size_axis, tuple(sizes), build, declared, repeats, flops)
    return deco


