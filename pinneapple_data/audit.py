def audit_zoo_dataset(name: str, *, offline: bool | None = None, **kw) -> AuditCard:
    """Audit a ``pp.datasets`` entry with the physics and constraints its catalog entry states."""
    from pinneapple_hub.zoo import datasets as zd
    info = zd.info(name)
    splits = {s: dict(d) for s, d in zd.load(name, offline=offline).items()}
    units = {c: (v.get("unit") if isinstance(v, dict) else v[0]) for c, v in info.columns.items()}
    desc = {c: (v.get("description", "") if isinstance(v, dict) else v[1]) for c, v in info.columns.items()}
    text = " ".join([desc_ for desc_ in desc.values()] + [str(v) for v in info.splits.values()])
    kw.setdefault("missing_documented", [c for c in units if f"{c} not recorded" in text or
                                         ("NaN" in desc[c] and "not" in desc[c])])
    args = {**ZOO_AUDIT.get(name, {}), **kw}
    if "inputs" not in args:
        args["inputs"] = [c for c in units if c != "index"]
    return audit_dataset(splits, name=name, units=units, **args)
