"""Physics audit of a training dataset: does the data solve its PDE? Split leakage, near duplicates, diversity and
units (#700). NumPy/SciPy only.

A model trained on wrong data inherits the error and model-level checks may never see it. Two open bugs of a widely
used library show how: generated Darcy data that did not solve the documented equation (NVIDIA/physicsnemo#2036) and
permeability samples with far less diversity than documented (NVIDIA/physicsnemo#2035). This audit checks the data
itself, before anyone trains on it.

Data layout: a split is a mapping ``{column: array}`` whose first axis is the sample (``(n,)`` for tabular columns,
``(n, ny, nx)`` for fields), as returned by ``pp.datasets.load`` or an ``.npz`` with ``<split>__<column>`` keys.

Checks (each returns pass / fail / not applicable with its evidence):

``finite``        every value finite.
``physics``       per-sample consistency with the stated PDE in the dataset's own discretisation
                  (:class:`DatasetPhysics`). Built in: ``"darcy"`` (``-div(a grad u) = f``, ``u = 0`` on the unit
                  square, cell-centred, the discretisation of ``operator_benchmarks.darcy_2d`` and of the zoo set
                  ``darcy_2d_li2021``): the error of each stored ``u`` against the solution of the same discrete
                  problem, ``||u - A^-1 f|| / ||A^-1 f||`` (the residual measured in the ``A^-1`` norm), the boundary
                  values and the discrete flux balance. Distribution, robust outliers and the failing samples are
                  reported.
``constraints``   declared relations between columns that hold in every row (``"r_base_k_w > 0"``,
                  ``"source_width_mm == source_frac_w * base_width_mm"``).
``diversity``     effective number of distinct samples (participation ratio of the principal-component spectrum),
                  exact duplicates and near duplicates inside a split, and, when the generator is stated, the same
                  statistics and the mean radial spectrum of the inputs against freshly generated samples.
``leakage``       nearest-neighbour distance from each test sample to the training set, relative to the typical
                  distance between training samples; flagged pairs are listed.
``units``         every column with a unit in the metadata has a parseable unit, of the expected dimension when the
                  problem states one.

:func:`audit_dataset` returns an :class:`AuditCard` (JSON / markdown), :func:`audit_zoo_dataset` audits a zoo dataset
with the physics its catalog entry states.
"""
from __future__ import annotations

import importlib
import json
from collections.abc import Callable, Mapping, Sequence
from dataclasses import asdict, dataclass, field
from typing import Any

import numpy as np

__all__ = ["DatasetPhysics", "DARCY", "AuditCheck", "AuditCard", "DEFAULT_TOLERANCES", "audit_dataset",
           "effective_sample_count", "near_duplicates", "leakage", "darcy_consistency", "audit_zoo_dataset",
           "ZOO_AUDIT", "constraint_mask"]

PASS, WARN, FAIL, NA = "pass", "warn", "fail", "not-applicable"

#: Default limits.
#: ``physics``: relative error of a sample against the solution of its own discrete problem (data generated by another
#: consistent discretisation differ by its truncation error: 0.5 % at 32 x 32 for a contrast-20 coefficient);
#: ``bc``: RMS boundary values against those of the exact discrete solution, over max |u|; ``flux``: relative net
#: flux imbalance; ``duplicates`` / ``leakage``: fraction of samples allowed to
#: be (near) copies; ``near``: a pair closer than ``near`` x the median nearest-neighbour distance of the training
#: set is a near copy; ``diversity``: the effective sample count may not fall below this fraction of the generator's;
#: ``spectrum``: allowed factor between the input spectrum and the generator's, per band.
DEFAULT_TOLERANCES: dict[str, float] = {"physics": 2e-2, "bc": 2e-2, "flux": 2e-2, "duplicates": 0.0,
                                         "leakage": 0.0, "near": 1e-3, "diversity": 0.5, "spectrum": 2.0,
                                         "min_effective": 2.0}


def _mod(dotted: str):
    """Import a numpy-only module without its package ``__init__`` (torch) when the checker's loader is present."""
    try:
        from pinneapple_check._reuse import leaf
        return leaf(dotted)
    except ImportError:
        return importlib.import_module(dotted)


@dataclass
class AuditCheck:
    id: str
    status: str                     # pass | warn | fail | not-applicable
    summary: str
    value: Any = None
    threshold: Any = None
    evidence: dict[str, Any] = field(default_factory=dict)

    @property
    def passed(self) -> bool | None:
        return None if self.status == NA else self.status != FAIL


@dataclass
class AuditCard:
    dataset: str
    splits: dict[str, int]
    physics: str | None
    checks: list[AuditCheck]
    tolerances: dict[str, float]

    @property
    def decision(self) -> str:
        st = {c.status for c in self.checks}
        return FAIL if FAIL in st else WARN if WARN in st else PASS

    @property
    def passed(self) -> bool:
        return self.decision != FAIL

    def __getitem__(self, check_id: str) -> AuditCheck:
        return next(c for c in self.checks if c.id == check_id)

    def to_dict(self) -> dict[str, Any]:
        return {"schema": "dataset-audit/v1", "dataset": self.dataset, "splits": self.splits, "physics": self.physics,
                "decision": self.decision, "tolerances": self.tolerances,
                "checks": [_json(asdict(c)) for c in self.checks]}

    def to_json(self, path=None) -> str:
        s = json.dumps(self.to_dict(), indent=1)
        if path is not None:
            from pathlib import Path
            Path(path).write_text(s + "\n")
        return s

    def to_markdown(self) -> str:
        L = [f"### Dataset audit: {self.dataset} ({self.decision.upper()})", "",
             "Splits: " + ", ".join(f"{k} {v}" for k, v in self.splits.items())
             + (f"; physics: {self.physics}" if self.physics else ""), "", "| Check | Status | Result |", "|---|---|---|"]
        L += [f"| {c.id} | {c.status} | {c.summary} |" for c in self.checks]
        return "\n".join(L)

    def __str__(self) -> str:
        return "\n".join([f"dataset audit {self.dataset}: {self.decision.upper()}"]
                         + [f"  {c.status.upper():15s} {c.id}: {c.summary}" for c in self.checks])


def _json(x: Any) -> Any:
    if isinstance(x, dict):
        return {str(k): _json(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [_json(v) for v in x]
    if isinstance(x, np.generic):
        return x.item()
    if isinstance(x, np.ndarray):
        return x.tolist()
    if isinstance(x, float) and not np.isfinite(x):
        return str(x)
    return x


# ---------------------------------------------------------------------------------------------- physics
@dataclass
class DatasetPhysics:
    """Per-sample physics of a dataset. ``check(sample) -> {name: relative error}`` for one sample (a mapping of
    column -> array without the sample axis); ``tolerances`` maps each name to its limit (keys of
    :data:`DEFAULT_TOLERANCES` or numbers)."""
    name: str
    columns: Sequence[str]
    check: Callable[[Mapping[str, np.ndarray]], dict[str, float]]
    tolerances: dict[str, str | float]
    units: dict[str, str] = field(default_factory=dict)   # expected dimension of columns, e.g. {"u": "-"}


def darcy_consistency(a: np.ndarray, u: np.ndarray, f: float | np.ndarray = 1.0) -> dict[str, float]:
    """Darcy sample checks in the discretisation of ``operator_benchmarks.darcy_2d`` (cell-centred, ``h = 1/n``):
    ``solve`` = relative L2 distance of ``u`` to the solution of its own discrete problem; ``bc`` = RMS difference of
    the boundary values (linear extrapolation of the first two cells to each face) from those of that solution, over
    max |u| (the extrapolation itself is only accurate to the grid, 3.5 % of max |u| at 16 x 16 for the exact
    solution, so the comparison is with the exact discrete solution, not with zero); ``flux`` = net outward boundary
    flux (``2 a u`` per boundary face, the solver's own boundary flux) against the integral of ``f``."""
    ob = _mod("pinneapple_simulation.numerical_solvers.operator_benchmarks")
    a, u = np.asarray(a, float), np.asarray(u, float)
    ref = ob.darcy_2d(a, f)
    n = a.shape[0]
    h = 1.0 / n
    scale = max(float(np.abs(ref).max()), 1e-300)

    def faces(v):                                       # linear extrapolation of the first two cells to each face
        return np.concatenate([1.5 * v[0] - 0.5 * v[1], 1.5 * v[-1] - 0.5 * v[-2], 1.5 * v[:, 0] - 0.5 * v[:, 1],
                               1.5 * v[:, -1] - 0.5 * v[:, -2]])

    flux = sum(float((2 * a[s] * u[s]).sum()) for s in ((0, slice(None)), (-1, slice(None)), (slice(None), 0),
                                                         (slice(None), -1)))
    source = float(np.broadcast_to(np.asarray(f, float), (n, n)).sum() * h * h)
    return {"solve": float(np.linalg.norm(u - ref) / max(np.linalg.norm(ref), 1e-300)),
            "bc": float(np.sqrt(np.mean((faces(u) - faces(ref)) ** 2)) / scale),
            "flux": abs(flux - source) / max(abs(source), 1e-300)}


DARCY = DatasetPhysics(
    "darcy", ("a", "u"),
    lambda s: darcy_consistency(s["a"], s["u"], s.get("f", 1.0)),
    {"solve": "physics", "bc": "bc", "flux": "flux"},
)
BUILTIN_PHYSICS = {"darcy": DARCY}


# ---------------------------------------------------------------------------------------------- diversity
def _flat(x: np.ndarray) -> np.ndarray:
    x = np.asarray(x, float)
    return x.reshape(len(x), -1)


def _standardise(*xs: np.ndarray) -> list[np.ndarray]:
    ref = xs[0]
    mu, sd = ref.mean(0), ref.std(0)
    sd = np.where(sd > 0, sd, 1.0)
    return [(x - mu) / sd for x in xs]


def effective_sample_count(x: np.ndarray) -> float:
    """Participation ratio ``(sum l)^2 / sum l^2`` of the principal-component spectrum of the samples (rows): about
    the number of independent directions the samples span; 1 when every sample is a multiple of one pattern."""
    X = _flat(x)
    X = X - X.mean(0)
    if len(X) > X.shape[1]:
        lam = np.linalg.eigvalsh(X.T @ X)
    else:
        lam = np.linalg.eigvalsh(X @ X.T)
    lam = np.clip(lam, 0, None)
    return float(lam.sum() ** 2 / max((lam ** 2).sum(), 1e-300))


def _nn(a: np.ndarray, b: np.ndarray | None = None, chunk: int = 512) -> tuple[np.ndarray, np.ndarray]:
    """Nearest neighbour of each row of ``a`` in ``b`` (in ``a`` itself, excluding the row, when ``b`` is None)."""
    same = b is None
    b = a if same else b
    b2 = (b ** 2).sum(1)
    d_out, i_out = np.empty(len(a)), np.empty(len(a), int)
    for s in range(0, len(a), chunk):
        A = a[s:s + chunk]
        d2 = (A ** 2).sum(1)[:, None] + b2[None, :] - 2 * A @ b.T
        if same:
            d2[np.arange(len(A)), np.arange(s, s + len(A))] = np.inf
        j = np.argmin(d2, axis=1)
        d_out[s:s + chunk] = np.sqrt(np.maximum(d2[np.arange(len(A)), j], 0.0))
        i_out[s:s + chunk] = j
    return d_out, i_out


def near_duplicates(x: np.ndarray, near: float = 1e-3) -> dict[str, Any]:
    """Exact and near duplicates inside one set (rows), relative to the median nearest-neighbour distance."""
    X = _flat(x)
    if len(X) < 2:
        return {"n": len(X), "exact": 0, "near": 0, "pairs": [], "median_nn": float("nan")}
    d, j = _nn(X)
    med = float(np.median(d))
    exact = d <= 1e-12 * max(float(np.abs(X).max()), 1.0)
    close = d <= near * med if med > 0 else exact
    pairs = [(int(i), int(j[i]), float(d[i])) for i in np.nonzero(close)[0] if i < j[i] or not close[j[i]]]
    return {"n": len(X), "exact": int(exact.sum()), "near": int(close.sum()), "pairs": pairs[:20], "median_nn": med}


def leakage(train: np.ndarray, test: np.ndarray, near: float = 1e-3) -> dict[str, Any]:
    """Nearest training sample of each test sample; a test sample closer than ``near`` x the median training
    nearest-neighbour distance is a (near) copy."""
    tr, te = _flat(train), _flat(test)
    d_tr, _ = _nn(tr)
    med = float(np.median(d_tr))
    d, j = _nn(te, tr)
    ratio = d / med if med > 0 else np.where(d > 0, np.inf, 0.0)
    flagged = np.nonzero(ratio <= near)[0]
    return {"n_test": len(te), "n_flagged": int(len(flagged)), "fraction": float(len(flagged) / max(len(te), 1)),
            "pairs": [(int(i), int(j[i]), float(ratio[i])) for i in flagged[:20]],
            "median_train_nn": med, "min_ratio": float(ratio.min()) if len(ratio) else float("nan")}


def _radial_spectrum(x: np.ndarray) -> np.ndarray:
    """Shell-summed spectrum of the sample-mean-removed fields, averaged over the samples."""
    x = np.asarray(x, float)
    F = np.abs(np.fft.fftn(x - x.mean(0), axes=tuple(range(1, x.ndim)))) ** 2
    grids = np.meshgrid(*[np.fft.fftfreq(n) * n for n in x.shape[1:]], indexing="ij")
    k = np.rint(np.sqrt(sum(g ** 2 for g in grids))).astype(int)
    E = np.bincount(k.ravel(), weights=F.mean(0).ravel())
    return E[: min(x.shape[1:]) // 2 + 1]


# ---------------------------------------------------------------------------------------------- the audit
_CONSTRAINT_FUNCTIONS = {"abs": np.abs, "sqrt": np.sqrt, "exp": np.exp, "log": np.log, "minimum": np.minimum,
                         "maximum": np.maximum, "floor": np.floor, "round": np.round}


def _constraint(expr: str, cols: Mapping[str, np.ndarray]) -> np.ndarray:
    # interpreted by pinneapple_data.expressions, never eval(): the constraints come from uploaded datasets
    from pinneapple_data.expressions import evaluate
    env = {k: np.asarray(v, float) for k, v in cols.items() if np.asarray(v).dtype.kind in "fiub"}
    env["pi"] = np.pi
    if "==" in expr:                                   # equality to a relative 1e-6
        lhs, rhs = expr.split("==", 1)
        a = evaluate(lhs, env, _CONSTRAINT_FUNCTIONS)
        b = evaluate(rhs, env, _CONSTRAINT_FUNCTIONS)
        a, b = np.broadcast_arrays(np.asarray(a, float), np.asarray(b, float))
        return np.abs(a - b) <= 1e-6 * np.maximum(np.abs(b), 1e-12) + 1e-12
    return np.asarray(evaluate(expr, env, _CONSTRAINT_FUNCTIONS), bool)


def constraint_mask(expr: str, cols: Mapping[str, np.ndarray]) -> np.ndarray:
    """Where the declared relation ``expr`` (``"Cd > 0"``, ``"abs(u) <= 1"``, ``"a == b * c"`` to 1e-6 relative)
    holds, element-wise over ``cols``: the evaluator the ``constraints`` check uses, for checking predictions too."""
    return _constraint(expr, cols)


def _tol(t: dict, v: str | float) -> float:
    return float(t[v]) if isinstance(v, str) else float(v)


def _robust_outliers(v: np.ndarray, k: float = 5.0) -> list[int]:
    med = np.median(v)
    mad = np.median(np.abs(v - med)) * 1.4826
    if mad <= 0:
        return []
    return [int(i) for i in np.nonzero((v - med) / mad > k)[0]]


def audit_dataset(splits: Mapping[str, Mapping[str, np.ndarray]], *, name: str = "dataset",
                  physics: DatasetPhysics | str | None = None, inputs: Sequence[str] | None = None,
                  units: Mapping[str, str] | None = None, expected_units: Mapping[str, str] | None = None,
                  constraints: Sequence[str] = (), generator: Callable[[int, int], np.ndarray] | None = None,
                  train: str = "train", test: str = "test", tolerances: Mapping[str, float] | None = None,
                  missing_documented: Sequence[str] = (),
                  duplicate_splits: Sequence[str] = ("train", "val", "cal", "test"),
                  max_physics_samples: int | None = 64, seed: int = 0) -> AuditCard:
    """Audit ``splits`` (``{split: {column: array}}``).

    ``inputs``: the columns that identify a sample for diversity and leakage (default: the physics' first column,
    else every numeric column). ``missing_documented``: columns whose NaN entries the metadata documents as "not
    recorded". ``duplicate_splits``: the splits checked for duplicates (a grid study repeats one case on purpose). ``generator(n, seed) -> (n, ...)`` draws inputs from the stated generator (for the
    diversity and spectrum comparison). ``max_physics_samples``: samples per split checked against the physics (a
    random subset; ``None`` for all), since each check may solve the problem."""
    tol = {**DEFAULT_TOLERANCES, **(tolerances or {})}
    phys = BUILTIN_PHYSICS[physics] if isinstance(physics, str) else physics
    checks: list[AuditCheck] = []
    sizes = {s: len(next(iter(d.values()))) for s, d in splits.items() if d}
    # ---- finite: infinities fail; NaN is a missing value (a warning, "documented" when the metadata says so)
    inf, nan = {}, {}
    for s, d in splits.items():
        for c, v in d.items():
            a = np.asarray(v)
            if a.dtype.kind in "fiub":
                a = a.astype(float)
                if np.isinf(a).any():
                    inf[f"{s}/{c}"] = int(np.isinf(a).sum())
                if np.isnan(a).any():
                    nan[f"{s}/{c}"] = int(np.isnan(a).sum())
    documented = {k for k in nan if k.split("/", 1)[1] in set(missing_documented)}
    if inf:
        checks.append(AuditCheck("finite", FAIL, "infinite values in " + ", ".join(f"{k} ({v})" for k, v in inf.items()),
                                 evidence={"inf": inf, "nan": nan}))
    elif nan:
        checks.append(AuditCheck("finite", WARN, "missing values (NaN) in " + ", ".join(
            f"{k} ({v}{', documented' if k in documented else ''})" for k, v in nan.items()),
            evidence={"nan": nan, "documented": sorted(documented)}))
    else:
        checks.append(AuditCheck("finite", PASS, "every value finite"))
    # ---- physics
    if phys is None:
        checks.append(AuditCheck("physics", NA, "no PDE stated for this dataset"))
    else:
        rng = np.random.default_rng(seed)
        per: dict[str, dict[str, list]] = {}
        failing: list[dict] = []
        for s, d in splits.items():
            if not all(c in d for c in phys.columns):
                continue
            n = len(d[phys.columns[0]])
            idx = np.arange(n) if max_physics_samples is None or n <= max_physics_samples else \
                np.sort(rng.choice(n, max_physics_samples, replace=False))
            for i in idx:
                r = phys.check({c: np.asarray(v)[i] for c, v in d.items()})
                for k, v in r.items():
                    per.setdefault(k, {}).setdefault(s, []).append(v)
                over = {k: v for k, v in r.items() if v > _tol(tol, phys.tolerances.get(k, "physics"))}
                if over:
                    failing.append({"split": s, "sample": int(i), **over})
        if not per:
            checks.append(AuditCheck("physics", NA, f"columns {list(phys.columns)} not in the data"))
        for k, by in per.items():
            v = np.concatenate([np.asarray(x) for x in by.values()])
            lim = _tol(tol, phys.tolerances.get(k, "physics"))
            nbad = int((v > lim).sum())
            outl = _robust_outliers(v)
            checks.append(AuditCheck(
                f"physics.{k}", FAIL if nbad else PASS,
                f"{phys.name} {k}: median {np.median(v):.3g}, max {v.max():.3g} over {len(v)} samples; "
                f"{nbad} above {lim:g}", value=float(v.max()), threshold=lim,
                evidence={"median": float(np.median(v)), "p95": float(np.percentile(v, 95)), "max": float(v.max()),
                          "n_checked": int(len(v)), "n_failing": nbad, "robust_outliers": len(outl),
                          "failing_samples": [x for x in failing if k in x][:20]}))
    # ---- constraints
    for expr in constraints:
        viol, n = 0, 0
        for d in splits.values():
            try:
                ok = _constraint(expr, d)
            except NameError:
                continue
            viol += int((~ok).sum())
            n += ok.size
        if n == 0:
            checks.append(AuditCheck(f"constraint: {expr}", NA, "columns not in the data"))
        else:
            checks.append(AuditCheck(f"constraint: {expr}", FAIL if viol else PASS, f"{viol} of {n} rows violate it",
                                     value=viol, threshold=0))
    # ---- diversity, duplicates, leakage
    def numeric(d: Mapping[str, np.ndarray], c: str) -> bool:
        return c in d and c != "index" and np.asarray(d[c]).dtype.kind in "fiub"

    def columns(d: Mapping[str, np.ndarray]) -> list[str]:
        cols = list(inputs) if inputs else ([phys.columns[0]] if phys else list(d))
        return [c for c in cols if numeric(d, c)]

    X = {s: np.concatenate([_flat(d[c]) for c in columns(d)], axis=1) for s, d in splits.items() if columns(d)}
    # tabular samples (one number per column) are standardised with the training split, so no column dominates
    tabular = all(np.asarray(splits[s][c]).ndim == 1 for s in X for c in columns(splits[s]))
    if tabular and train in X:
        keys = [train] + [s for s in X if s != train]
        X = dict(zip(keys, _standardise(*[X[k] for k in keys]), strict=True))
    if train in X:
        dup = {s: near_duplicates(x, tol["near"]) for s, x in X.items() if s in duplicate_splits}
        frac = max(v["near"] / max(v["n"], 1) for v in dup.values())
        st = FAIL if frac > tol["duplicates"] else PASS
        checks.append(AuditCheck("diversity.duplicates", st,
                                 "; ".join(f"{s}: {v['exact']} exact, {v['near']} near copies of {v['n']}"
                                           for s, v in dup.items()), value=frac, threshold=tol["duplicates"],
                                 evidence={s: {k: v[k] for k in ("exact", "near", "pairs", "median_nn")}
                                           for s, v in dup.items()}))
        eff = effective_sample_count(X[train])
        ev: dict[str, Any] = {"effective": eff, "n": len(X[train])}
        if generator is not None:
            g = np.asarray(generator(min(len(X[train]), 512), seed + 1), float)
            eff_g = effective_sample_count(g)
            ratio = eff / max(eff_g, 1e-300)
            ev.update(generator_effective=eff_g, ratio=ratio)
            st = FAIL if ratio < tol["diversity"] else PASS
            summ = f"effective sample count {eff:.3g} (generator: {eff_g:.3g}, ratio {ratio:.2f})"
            checks.append(AuditCheck("diversity.effective", st, summ, value=ratio, threshold=tol["diversity"],
                                     evidence=ev))
            xin = np.asarray(splits[train][inputs[0] if inputs else phys.columns[0]], float) if (inputs or phys) \
                else None
            if xin is not None and xin.ndim >= 2 and g.shape[1:] == xin.shape[1:]:
                Ed, Eg = _radial_spectrum(xin), _radial_spectrum(g)
                k = np.arange(1, min(len(Ed), len(Eg)))
                k = k[Eg[k] > 1e-12 * Eg[1:].max()]
                r = Ed[k] / Eg[k]
                worst = float(np.max(np.maximum(r, 1 / np.maximum(r, 1e-300))))
                checks.append(AuditCheck("diversity.spectrum", FAIL if worst > tol["spectrum"] else PASS,
                                         f"input spectrum within a factor {worst:.3g} of the generator's "
                                         f"(shells 1-{int(k.max())})", value=worst, threshold=tol["spectrum"],
                                         evidence={"ratio_per_shell": r.tolist()}))
        else:
            st = FAIL if eff < tol["min_effective"] else PASS
            checks.append(AuditCheck("diversity.effective", st, f"effective sample count {eff:.3g} of {len(X[train])} "
                                     "(no generator stated: only a collapse to one pattern is flagged)", value=eff,
                                     threshold=tol["min_effective"], evidence=ev))
    else:
        checks.append(AuditCheck("diversity.duplicates", NA, f"no {train!r} split"))
    if train in X and test in X:
        lk = leakage(X[train], X[test], tol["near"])
        st = FAIL if lk["fraction"] > tol["leakage"] else PASS
        checks.append(AuditCheck("leakage", st, f"{lk['n_flagged']} of {lk['n_test']} {test} samples are (near) copies "
                                 f"of {train} samples (closest: {lk['min_ratio']:.3g} x the median train spacing)",
                                 value=lk["fraction"], threshold=tol["leakage"], evidence=lk))
    else:
        checks.append(AuditCheck("leakage", NA, f"needs both {train!r} and {test!r} splits"))
    # ---- units
    if units:
        pu = _mod("pinneapple_data.physical_units")
        bad_u, mism = [], []
        exp = {**(phys.units if phys else {}), **(expected_units or {})}
        for c, u in units.items():
            parsed = pu.try_parse_unit("1" if u in ("-", "", None) else u)
            if parsed is None:
                bad_u.append(f"{c} [{u}]")
                continue
            if c in exp:
                want = pu.try_parse_unit(exp[c] if exp[c] not in ("-", "") else "1")
                if want is not None and parsed is not None and want.dim != parsed.dim:
                    mism.append(f"{c}: {u}, expected {exp[c]}")
        st = FAIL if (bad_u or mism) else PASS
        checks.append(AuditCheck("units", st, "; ".join(bad_u + mism) or f"{len(units)} column units parse"
                                 + (f", {len([c for c in units if c in exp])} match the problem" if exp else ""),
                                 evidence={"unparseable": bad_u, "mismatch": mism}))
    else:
        checks.append(AuditCheck("units", NA, "no unit metadata"))
    return AuditCard(name, sizes, phys.name if phys else None, checks, tol)


