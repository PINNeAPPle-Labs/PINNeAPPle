"""The stdio MCP server: ``pinneapple-mcp`` or ``python -m pinneapple_mcp``.

Works with the official MCP Python SDK 2.x (``MCPServer``) and 1.x (``FastMCP``). Every tool has a typed signature,
so its input JSON schema is generated by the SDK; every tool returns a JSON object.
"""
from __future__ import annotations

import argparse
import os
from typing import Annotated, Any, Literal

from pydantic import Field

from . import tools as T
from .config import Config, get_config, set_config

INSTRUCTIONS = """PINNeAPPle: solve, benchmark and validate physics problems (PINNs, classical solvers, surrogates).
Start with capabilities and list_methods; zoo_list shows pre-trained, verified models (use them before training
your own). solve and benchmark start a job: poll job_status with the job_id (or pass
wait_seconds). Never report a result without its trust card: every solve/benchmark result carries the physics checks
(PDE residual, boundary conditions, conservation, reference error, applicability) and a decision APPROVED / REVIEW /
REJECT. Use trust_card to check any field you have (a file or inline values). design turns a plain-language goal into
a verified design package, or says what is missing / out of scope. Results are saved under the working
directory; the paths are in each result."""

Problem = Annotated[dict[str, Any], Field(description=(
    "A preset {'preset': name, 'preset_kwargs': {...}} or a box problem {'name', 'domain': {coord: [lo, hi]}, "
    "'fields': [...], 'pde': kind (laplace, poisson, heat_equation, burgers, ...), 'params': {...}, "
    "'source': expr, 'bcs': [{'kind': 'dirichlet', 'field', 'on': 'x_min'|'x_max'|'x_boundary'|'boundary', "
    "'value': number or expr}], 'ics': [{'field', 'value'}], 'exact': expr}. Expressions use the coordinate "
    "names, pi, e and numpy functions, e.g. 'sin(pi*x)*sinh(pi*y)/sinh(pi)'."))]
Wait = Annotated[float, Field(ge=0, le=3600, description="Seconds to wait for the job to finish before returning")]
MaxSeconds = Annotated[float | None, Field(gt=0, description="Wall-time limit of the job (capped by the server)")]


def _register(server) -> None:
    @server.tool()
    def capabilities() -> dict[str, Any]:
        """Version, device, optional APIs present (benchmark, zoo, datasets, geometries), limits and working
        directory of this PINNeAPPle installation."""
        return T.capabilities()

    @server.tool()
    def list_methods(
        category: Annotated[Literal["all", "solver", "training", "equation", "problem"],
                            Field(description="Catalog category")] = "all",
        validated_only: Annotated[bool, Field(description="Only items validated against a reference")] = False,
    ) -> dict[str, Any]:
        """Solve methods usable by solve/benchmark (by kind) and the method catalog with each item's validation
        status (validated / tested, no reference / no test)."""
        return T.list_methods(category, validated_only)

    @server.tool()
    def describe_method(
        method: Annotated[str, Field(description="A solve method (pinn, fem, analytic, reference, exact, external) "
                                                 "or a catalog id (S2, T4, E10, P3, ...)")],
    ) -> dict[str, Any]:
        """Options and documentation of a solve method, or code, references, validation status and evidence of a
        catalog item."""
        return T.describe_method(method)

    @server.tool()
    def list_presets(
        contains: Annotated[str | None, Field(description="Substring filter")] = None,
    ) -> dict[str, Any]:
        """Problem presets usable as {'preset': name}."""
        return T.list_presets(contains)

    @server.tool()
    def solve(
        problem: Problem,
        method: Annotated[str, Field(description="Solve method: pinn, fem, analytic, reference, exact")] = "pinn",
        options: Annotated[dict[str, Any] | None, Field(description=(
            "Method options, e.g. pinn: {'epochs': 2000, 'hidden_dim': 64, 'n_layers': 4, 'lr': 1e-3, "
            "'n_collocation': 2048, 'seed': 0, 'device': 'auto'}; fem: {'n': 32}"))] = None,
        reference: Annotated[str | None, Field(description=(
            "Reference for the error: 'exact' (the problem's expression), a method name (fem, analytic, "
            "reference) or null for automatic"))] = None,
        reference_options: Annotated[dict[str, Any] | None, Field(description="Options of the reference method")]
        = None,
        grid_points_per_axis: Annotated[int, Field(ge=5, le=1001, description="Evaluation grid per axis")] = 41,
        max_seconds: MaxSeconds = None,
        wait_seconds: Wait = 0.0,
    ) -> dict[str, Any]:
        """Solve a problem with one method as a job. The result has the metrics against the reference, the physics
        checks, the trust card (APPROVED / REVIEW / REJECT) and the paths of prediction.npz, field.png and the
        trust card. Returns the job status; poll job_status."""
        return T.solve(problem, method, options, reference, reference_options, grid_points_per_axis, max_seconds,
                       wait_seconds)

    @server.tool()
    def trust_card(
        file: Annotated[str | None, Field(description=(
            "Prediction file inside the allowed roots: .npz (field arrays + axis_<coord> arrays, optional "
            "ref_<field>), .npy or .csv"))] = None,
        field: Annotated[str | None, Field(description="Field name in the .npz")] = None,
        grid: Annotated[dict[str, list[float]] | None, Field(description="Axes {coord: [values]} in array order")]
        = None,
        values: Annotated[list[Any] | None, Field(description="Inline field values (nested lists)")] = None,
        pde: Annotated[Literal["laplace", "poisson", "heat"] | None, Field(description="Equation to check")]
        = None,
        source: Annotated[str | None, Field(description="Source term f as an expression")] = None,
        alpha: Annotated[float, Field(description="Diffusivity for pde='heat'")] = 1.0,
        dirichlet: Annotated[dict[str, Any] | None, Field(description=(
            "Boundary values per face {'x_min': 0, 'y_max': 'sin(pi*x)'}"))] = None,
        reference: Annotated[str | None, Field(description="Closed-form reference as an expression")] = None,
        reference_file: Annotated[str | None, Field(description="Reference field file (same grid)")] = None,
        value_range: Annotated[list[float] | None, Field(description="Physical range [lo, hi]")] = None,
        train_bounds: Annotated[dict[str, list[float]] | None, Field(description=(
            "Training bounds {coord: [lo, hi]} for the applicability (OOD) check"))] = None,
        tolerances: Annotated[dict[str, float] | None, Field(description=(
            "Overrides of residual, bc, conservation, max_principle, reference, ood"))] = None,
        name: Annotated[str, Field(description="Label of the card")] = "field",
    ) -> dict[str, Any]:
        """Physics checks of a field on a grid (finite values, PDE residual, boundary conditions, conservation,
        maximum principle, reference error, applicability) and the trust card with its decision. Saves the card
        (markdown and JSON) in the working directory."""
        return T.trust_card(file, field, grid, values, pde, source, alpha, dirichlet, reference, reference_file,
                            value_range, train_bounds, tolerances, name)

    @server.tool()
    def benchmark(
        problem: Problem,
        methods: Annotated[list[str], Field(description="Solve methods to compare")] = ["pinn", "fem"],  # noqa: B006
        budget: Annotated[dict[str, Any] | None, Field(description=(
            "Equal budget of every neural run: {'epochs': 1000, 'n_collocation': 2048}"))] = None,
        seeds: Annotated[int, Field(ge=1, le=10, description="Seeds per neural method")] = 1,
        reference: Annotated[str | None, Field(description="'exact', a method name or null")] = None,
        options: Annotated[dict[str, dict[str, Any]] | None, Field(description="Per-method options")] = None,
        grid_points_per_axis: Annotated[int, Field(ge=5, le=1001)] = 41,
        max_seconds: MaxSeconds = None,
        wait_seconds: Wait = 0.0,
    ) -> dict[str, Any]:
        """Equal-budget comparison of methods on one problem as a job: relative L2 mean and spread over seeds,
        training time, and a trust card per run; writes table.md. Returns the job status; poll job_status."""
        return T.benchmark(problem, methods, budget, seeds, reference, options, grid_points_per_axis, max_seconds,
                           wait_seconds)

    @server.tool()
    def design(
        text: Annotated[str, Field(description="The goal in plain language, e.g. 'a bracket that holds 2 kN'")],
        answers: Annotated[dict[str, Any] | None, Field(description=(
            "Answers to follow-up questions: {slot: value} in the slot's unit or {slot: [value, unit]}, e.g. "
            "{'arm_length': [100, 'mm']}"))] = None,
        verify: Annotated[bool, Field(description="Run the full-fidelity solver on the chosen design")] = True,
        seed: Annotated[int, Field(ge=0, description="Seed (same seed, same design)")] = 0,
        max_seconds: MaxSeconds = None,
        wait_seconds: Wait = 0.0,
    ) -> dict[str, Any]:
        """Design from intent: returns at once 'out_of_scope' (with what would be needed) or 'needs_input' (the
        questions to answer), otherwise starts a job whose result is the design package: verdict with probability,
        design, margins per failure mode, full-solver verification, operating window, bill of materials, limits and
        the files (report.html, STEP / STL / glTF). Poll job_status."""
        return T.design(text, answers, verify, seed, max_seconds, wait_seconds)

    @server.tool()
    def zoo_list(task: Annotated[str | None, Field(description="Filter by task")] = None) -> dict[str, Any]:
        """Pre-trained, verified models of the model zoo (inputs, outputs, validity range, held-out errors, licence)
        and the datasets of the dataset hub."""
        return T.zoo_list(task)

    @server.tool()
    def zoo_predict(
        name: Annotated[str, Field(description="Zoo model name, e.g. airfoil_cst_rans_mlp")],
        inputs: Annotated[dict[str, Any], Field(description=(
            "{input name: value or list of values}, every input of the model (see zoo_list)"))],
    ) -> dict[str, Any]:
        """Predictions of a zoo model, with which rows are inside its validity range."""
        return T.zoo_predict(name, inputs)

    @server.tool()
    def zoo_validate(
        name: Annotated[str, Field(description="Zoo model name")],
        inputs: Annotated[dict[str, Any] | None, Field(description="Optional query inputs to check against the "
                                                                   "validity range")] = None,
    ) -> dict[str, Any]:
        """Trust report of a zoo model: card metrics reproduced, acceptance limits, physics checks, validity range
        of the query; decision APPROVED / REVIEW / REJECT."""
        return T.zoo_validate(name, inputs)

    @server.tool()
    def job_status(job_id: Annotated[str, Field(description="Job id from solve or benchmark")],
                   wait_seconds: Wait = 0.0) -> dict[str, Any]:
        """Status of a job (queued, running, done, failed, timeout, cancelled, lost); when done, its result and the
        paths of its files."""
        return T.job_status(job_id, wait_seconds)

    @server.tool()
    def list_jobs(limit: Annotated[int, Field(ge=1, le=200)] = 20) -> dict[str, Any]:
        """Most recent jobs with their status."""
        return T.list_jobs(limit)

    @server.tool()
    def cancel_job(job_id: Annotated[str, Field(description="Job id")]) -> dict[str, Any]:
        """Stop a running job."""
        return T.cancel_job(job_id)


def build_server(config: Config | None = None):
    """The MCP server object (SDK 2.x ``MCPServer`` or 1.x ``FastMCP``) with every PINNeAPPle tool."""
    if config is not None:
        set_config(config)
    get_config().ensure()
    try:
        from mcp.server.mcpserver import MCPServer as _Server
    except ImportError:
        try:
            from mcp.server.fastmcp import FastMCP as _Server
        except ImportError as exc:
            raise ImportError('the MCP server needs the MCP SDK: pip install "pinneapple[mcp]"') from exc
    server = _Server("pinneapple", instructions=INSTRUCTIONS)
    _register(server)
    return server


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(prog="pinneapple-mcp", description="PINNeAPPle MCP server (stdio)")
    ap.add_argument("--workdir", help="results and jobs directory (PINNEAPPLE_MCP_WORKDIR)")
    ap.add_argument("--max-seconds", type=float, help="wall-time limit per job (PINNEAPPLE_MCP_MAX_SECONDS)")
    ap.add_argument("--max-memory-mb", type=int, help="memory limit per job (PINNEAPPLE_MCP_MAX_MEMORY_MB)")
    ap.add_argument("--max-jobs", type=int, help="concurrent jobs (PINNEAPPLE_MCP_MAX_JOBS)")
    ap.add_argument("--allow-network", action="store_true", help="let jobs open network connections")
    ap.add_argument("--roots", help=f"readable roots, separated by '{os.pathsep}' (PINNEAPPLE_MCP_ROOTS)")
    a = ap.parse_args(argv)
    if a.workdir:
        os.environ["PINNEAPPLE_MCP_WORKDIR"] = a.workdir
    if a.max_seconds:
        os.environ["PINNEAPPLE_MCP_MAX_SECONDS"] = str(a.max_seconds)
    if a.max_memory_mb:
        os.environ["PINNEAPPLE_MCP_MAX_MEMORY_MB"] = str(a.max_memory_mb)
    if a.max_jobs:
        os.environ["PINNEAPPLE_MCP_MAX_JOBS"] = str(a.max_jobs)
    if a.allow_network:
        os.environ["PINNEAPPLE_MCP_ALLOW_NETWORK"] = "1"
    if a.roots:
        os.environ["PINNEAPPLE_MCP_ROOTS"] = a.roots
    os.environ.setdefault("MPLBACKEND", "Agg")
    server = build_server(Config())
    server.run("stdio")


if __name__ == "__main__":
    main()
