"""3-D pictures of preset results on the library's studio scene.

Meshes for the shapes presets need (box, tube along a path, extruded section), the self-contained three.js viewer
(``web_viewer(single_file=True)``) and PNG stills of it per field taken in headless Chromium. Blender Cycles renders
(``pp.viz.render``) are used when ``bpy`` is importable; otherwise the stills come from the viewer.
"""
from __future__ import annotations

import os
from collections.abc import Sequence

import numpy as np

from pinneapple_tools.visualization.studio.scene import Scene, Surface

__all__ = ["box", "tube", "extrude", "merge", "field_on", "stills", "Scene", "Surface"]


def box(lo, hi, n=(1, 1, 1)):
    """Closed axis-aligned box from ``lo`` to ``hi`` with ``n`` cells per side on each face; returns (V, F)."""
    lo, hi = np.asarray(lo, float), np.asarray(hi, float)
    Vs, Fs, off = [], [], 0
    for ax in range(3):
        for side in (0, 1):
            a, b = [i for i in range(3) if i != ax]
            na, nb = n[a], n[b]
            s = np.linspace(lo[a], hi[a], na + 1)
            t = np.linspace(lo[b], hi[b], nb + 1)
            S, T = np.meshgrid(s, t, indexing="ij")
            V = np.zeros((S.size, 3))
            V[:, a], V[:, b] = S.ravel(), T.ravel()
            V[:, ax] = hi[ax] if side else lo[ax]
            idx = np.arange(S.size).reshape(na + 1, nb + 1)
            q = np.stack([idx[:-1, :-1], idx[1:, :-1], idx[1:, 1:], idx[:-1, 1:]], -1).reshape(-1, 4)
            flip = (side == 1) == (ax == 1)
            tri = np.r_[q[:, [0, 1, 2]], q[:, [0, 2, 3]]]
            if flip:
                tri = tri[:, ::-1]
            Vs.append(V)
            Fs.append(tri + off)
            off += len(V)
    return np.vstack(Vs), np.vstack(Fs)


def tube(path, radius, n_around: int = 16):
    """Open tube of ``radius`` (scalar or one per path point) along the polyline ``path`` (N x 3); returns
    (V, F, s) with ``s`` the index of the path point of each vertex (to put per-point values on the surface)."""
    P = np.asarray(path, float)
    r = np.broadcast_to(np.asarray(radius, float), (len(P),))
    T = np.gradient(P, axis=0)
    T /= np.linalg.norm(T, axis=1, keepdims=True)
    ref = np.array([0.0, 0.0, 1.0]) if abs(T[0, 2]) < 0.9 else np.array([1.0, 0.0, 0.0])
    N = np.cross(T[0], ref)
    N /= np.linalg.norm(N)
    ang = np.linspace(0, 2 * np.pi, n_around, endpoint=False)
    V, S = [], []
    for i in range(len(P)):
        N = N - (N @ T[i]) * T[i]                         # parallel transport of the normal
        N /= np.linalg.norm(N)
        Bv = np.cross(T[i], N)
        ring = P[i] + r[i] * (np.cos(ang)[:, None] * N + np.sin(ang)[:, None] * Bv)
        V.append(ring)
        S.append(np.full(n_around, i))
    V = np.vstack(V)
    F = []
    for i in range(len(P) - 1):
        for j in range(n_around):
            a, b = i * n_around + j, i * n_around + (j + 1) % n_around
            c, d = a + n_around, b + n_around
            F += [[a, b, d], [a, d, c]]
    return V, np.asarray(F), np.concatenate(S)


def extrude(section, x):
    """Prism of the closed 2-D polygon ``section`` (M x 2, in the y-z plane, counter-clockwise) along the stations
    ``x``; returns (V, F, i) with ``i`` the station index of each vertex. Ends are capped with a fan (convex or
    star-shaped sections)."""
    S = np.asarray(section, float)
    x = np.asarray(x, float)
    m = len(S)
    V = np.vstack([np.c_[np.full(m, xi), S] for xi in x])
    st = np.repeat(np.arange(len(x)), m)
    F = []
    for i in range(len(x) - 1):
        for j in range(m):
            a, b = i * m + j, i * m + (j + 1) % m
            F += [[a, b, b + m], [a, b + m, a + m]]
    c0, c1 = len(V), len(V) + 1
    V = np.vstack([V, [x[0], *S.mean(0)], [x[-1], *S.mean(0)]])
    st = np.r_[st, 0, len(x) - 1]
    last = (len(x) - 1) * m
    for j in range(m):
        F.append([c0, (j + 1) % m, j])
        F.append([c1, last + j, last + (j + 1) % m])
    return V, np.asarray(F), st


def merge(parts: Sequence[tuple]):
    """Concatenate (V, F[, values...]) meshes into one; returns the same tuple shape."""
    Vs, Fs, extra, off = [], [], None, 0
    for p in parts:
        V, F = p[0], p[1]
        Vs.append(V)
        Fs.append(F + off)
        off += len(V)
        if len(p) > 2:
            extra = [[] for _ in p[2:]] if extra is None else extra
            for k, a in enumerate(p[2:]):
                extra[k].append(np.asarray(a))
    out = (np.vstack(Vs), np.vstack(Fs))
    if extra:
        out += tuple(np.concatenate(e) for e in extra)
    return out


def stills(scene: Scene, out_dir: str, name: str, modes: Sequence[str] = (), size=(1100, 700),
           views: dict[str, str] | None = None, frame: int | None = None) -> dict[str, str | None]:
    """Write ``out_dir/<name>_viewer.html`` (self-contained, regenerated by the scripts, not committed) and one
    PNG per field in ``modes`` ("real" for the materials). Returns {mode: png path or None if no browser}."""
    from pinneapple_tools.visualization.studio.web import screenshot, web_viewer
    os.makedirs(out_dir, exist_ok=True)
    html = web_viewer(scene, out_dir, single_file=True, filename=f"{name}_viewer.html")
    pngs: dict[str, str | None] = {"viewer": html}
    page = html
    if scene.animation is not None and frame is None:          # stills of the static fields, not frame 0
        import copy
        static = copy.copy(scene)
        static.animation = None
        page = web_viewer(static, out_dir, single_file=True, filename=f".{name}_static.html")
    for m in modes or [None]:
        js = "studio.setMode('real')" if m == "real" else (f"studio.setMode('field', {m!r})" if m else None)
        if views and m in views:
            js = (js + ";" if js else "") + views[m]
        out = os.path.join(out_dir, f"{name}_3d{'_' + m if m else ''}.png")
        pngs[m or "default"] = screenshot(page, out, size=size, setup_js=js, frame=frame)
    if page != html:
        os.remove(page)
    return pngs


def field_on(idx: np.ndarray, values) -> np.ndarray:
    """Per-vertex values from per-station values (``idx`` from :func:`tube` / :func:`extrude`)."""
    return np.asarray(values, float)[idx]
