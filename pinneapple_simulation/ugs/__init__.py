"""Underground gas storage: a reference simulator, its verification, a benchmark and a deliverability optimiser.

The programme follows the UGS line of work that replaces a reservoir simulator with a neural operator
(Sirota et al., arXiv 2509.21485) -- on public and synthetic models, with our own numbers:

* :mod:`.pvt` -- the gas: z-factor (Papay, Hall-Yarborough), viscosity (Lee-Gonzalez-Eakin), formation volume
  factor and density;
* :mod:`.grid` -- a structured cartesian grid in one to three dimensions with heterogeneous permeability and
  porosity, and a one-dimensional radial grid for well tests;
* :mod:`.wells` -- completions with a Peaceman index, rate or bottom-hole-pressure control with limits, and
  injection/withdrawal schedules;
* :mod:`.simulator` -- the reference model: single-phase real gas, two-point flux in space, backward Euler in
  time, Newton with an analytic Jacobian, and the diagnostics an engineer reads first (average pressure, rate
  and bottom-hole pressure per well, gas in place, daily deliverability, measured mass-balance error);
* :mod:`.verification` -- the analytic references: the Theis line source, the pseudo-steady-state decline, the
  p/z material-balance line and the observed orders of accuracy;
* :mod:`.benchmark` -- synthetic scenarios generated by the simulator, a tank (material balance) baseline, the
  metrics, and what is still missing (the trained surrogate);
* :mod:`.optimization` -- peak daily deliverability under pressure, rate and inventory constraints, searched on
  the reference simulator and therefore verified by construction.

Quick start::

    from pinneapple_simulation.ugs import (
        CartesianGrid, Gas, Rock, Schedule, Period, Control, UGSSimulator, Well)

    grid = CartesianGrid((21, 21), (40.0, 40.0), permeability=1e-13, porosity=0.2)
    well = Well("P1", cell=0, bhp_min=5e6)
    sim = UGSSimulator(grid, Gas(T=320.0), Rock(cr=1e-9, p_ref=1.2e7), [well], p0=1.2e7)
    plan = Schedule((Period(30.0, {"P1": Control("rate", -0.2)}),))
    result = sim.run(plan)
    print(result.summary())
"""
