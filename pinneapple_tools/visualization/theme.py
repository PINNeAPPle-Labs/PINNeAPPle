_JS_HEADER = """// PINNeAPPle house theme -- generated by scripts/build_theme.py from
// pinneapple_tools/visualization/theme.json. Edit the JSON and rebuild; do not edit this file.
//
// Read by {consumer}. Stops are [position 0..1, [r, g, b] 0..255], the shape both viewers already ramp over.
"""


def as_js(consumer: str) -> str:
    """The theme as an ES module: the same values, in the shape a three.js viewer needs."""
    data = theme()
    maps = {name: {"kind": colormap_kind(name), "stops": stops_as_bytes(name)} for name in colormap_names()}
    payload = {
        "name": data["name"],
        "version": data["version"],
        "brand": data["brand"],
        "surface": data["surface"],
        "categorical": data["categorical"],
        "colormaps": maps,
        "fieldCmaps": data["field_cmaps"],
        "defaultCmap": field_cmap_name("velocity_magnitude"),
    }
    body = json.dumps(payload, indent=1, sort_keys=True)
    return _JS_HEADER.format(consumer=consumer) + f"\nexport const THEME = {body};\n\nexport default THEME;\n"


def as_css(dark: bool = False) -> str:
    """The theme as CSS custom properties for the apps' shared stylesheet."""
    s = surface(dark)
    b = brand()
    series = "\n".join(f"  --series-{i + 1}: {c};" for i, c in enumerate(palette()))
    return (":root {\n"
            f"  --house-ink: {b['ink']};\n"
            f"  --house-blue: {b['blue']};\n"
            f"  --house-ember: {b['ember']};\n"
            f"  --plot: {s['plot']};\n"
            f"  --paper: {s['paper']};\n"
            f"  --ink: {s['ink']};\n"
            f"  --muted: {s['muted']};\n"
            f"  --line: {s['line']};\n"
            f"{series}\n"
            "}\n")


def generated() -> dict:
    """Every generated artefact, path -> content. ``scripts/build_theme.py`` writes this mapping."""
    return {
        GENERATED["studio"]: as_js("the studio viewer and the apps (pinneapple_tools/visualization/studio/web)"),
        GENERATED["twin3d"]: as_js("the twin3d viewer (pinneapple_twin3d/viewer)"),
        GENERATED["apps"]: as_css(),
    }


def viewport(dark: bool = False) -> str:
    """The background of a 3-D plot: the one colour PyVista, the studio viewer and the twin3d viewer share."""
    return surface(dark)["plot"]


