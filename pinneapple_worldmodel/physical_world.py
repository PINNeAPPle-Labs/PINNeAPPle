G = 9.81


# ============================================================================================ scenes
def _ball_trajectory(x0, y0, vx, vy, e, radius, t, g=G):
    """Exact positions and velocities at times ``t`` of a ball under gravity bouncing on y = radius (restitution e,
    walls at x = 0 and x = width are not modelled: choose vx so the ball stays in view)."""
    X, Y, VX, VY, contact = [], [], [], [], []
    tt, x, y, uy = 0.0, x0, y0, vy
    bounces = []
    for tk in t:
        while True:
            # time to reach the floor from (y, uy): y + uy s - g s^2 / 2 = radius
            disc = uy * uy + 2 * g * (y - radius)
            s_hit = (uy + np.sqrt(max(disc, 0.0))) / g
            if tt + s_hit >= tk or abs(uy) < 1e-9 and y <= radius + 1e-12:
                break
            tt += s_hit
            x += vx * s_hit
            y = radius
            uy = -(uy - g * s_hit) * e
            bounces.append(tt)
            if abs(uy) < 1e-3:                             # at rest
                uy = 0.0
                break
        s = tk - tt
        if uy == 0.0 and y <= radius + 1e-12:
            X.append(x + vx * s)
            Y.append(radius)
            VX.append(vx)
            VY.append(0.0)
        else:
            X.append(x + vx * s)
            Y.append(max(y + uy * s - 0.5 * g * s * s, radius))
            VX.append(vx)
            VY.append(uy - g * s)
        contact.append(any(abs(b - tk) < 0.5 * (t[1] - t[0]) for b in bounces) if len(t) > 1 else False)
    return np.array(X), np.array(Y), np.array(VX), np.array(VY), np.array(contact), bounces


@dataclass
class Video:
    frames: np.ndarray                # (T, H, W) float in [0, 1]
    dt: float
    px_per_m: float
    labels: dict[str, Any] = field(default_factory=dict)
    params: dict[str, Any] = field(default_factory=dict)

    @property
    def n(self) -> int:
        return len(self.frames)


def _render(cx, cy, r_px, H, W, rng, prm):
    from scipy import ndimage
    yy, xx = np.mgrid[0:H, 0:W].astype(float)
    bg = prm["bg"] + prm["texture"] * (0.5 * np.sin(xx / prm["tex_scale"] + prm["tex_phase"])
                                       * np.cos(yy / (1.3 * prm["tex_scale"])))
    frames = []
    for x, y in zip(cx, cy, strict=True):
        d = np.sqrt((xx - x) ** 2 + (yy - y) ** 2)
        disk = np.clip(r_px + 0.5 - d, 0.0, 1.0)                       # antialiased disk
        img = bg * (1 - disk) + prm["fg"] * disk
        img = prm["gain"] * img
        if prm["defect"] is not None:
            x0, y0, w0 = prm["defect"]
            img[int(y0):int(y0 + w0), int(x0):int(x0 + w0)] = prm["bg"] * prm["gain"]
        if prm["blur"] > 0:
            k = np.exp(-0.5 * (np.arange(-3, 4) / prm["blur"]) ** 2)
            k /= k.sum()
            img = ndimage.convolve1d(ndimage.convolve1d(img, k, axis=0, mode="constant"), k, axis=1, mode="constant")
        img = img + rng.normal(0, prm["noise"], img.shape)
        frames.append(np.clip(img, 0, 1))
    return np.asarray(frames, np.float32)


def bouncing_ball_scene(*, seed: int = 0, T: int = 48, fps: float = 24.0, H: int = 64, W: int = 96,
                        randomize: bool = True, defect: bool = False, e: float | None = None) -> Video:
    """A thrown ball bouncing on the floor, rendered with domain randomization; exact labels."""
    rng = np.random.default_rng(seed)
    dt = 1.0 / fps
    world_w = 2.0                                                   # metres across the default view
    zoom = rng.uniform(0.85, 1.15) if randomize else 1.0
    px_per_m = W / world_w * zoom
    radius = 0.08
    e = float(rng.uniform(0.6, 0.9)) if e is None else e
    x0, y0 = rng.uniform(0.2, 0.5), rng.uniform(0.7, 1.1)
    vx, vy = rng.uniform(0.4, 0.7), rng.uniform(-0.5, 1.5)
    t = np.arange(T) * dt
    X, Y, VX, VY, contact, bounces = _ball_trajectory(x0, y0, vx, vy, e, radius, t)
    off = (rng.uniform(-6, 6), rng.uniform(-4, 4)) if randomize else (0.0, 0.0)
    cx = X * px_per_m + off[0]
    cy = H - 4 - Y * px_per_m + off[1]                              # floor 4 px above the bottom edge
    prm = {"bg": float(rng.uniform(0.1, 0.35)) if randomize else 0.2,
           "fg": float(rng.uniform(0.75, 0.95)) if randomize else 0.9,
           "gain": float(rng.uniform(0.8, 1.2)) if randomize else 1.0,
           "texture": float(rng.uniform(0.0, 0.08)) if randomize else 0.0,
           "tex_scale": float(rng.uniform(3, 9)), "tex_phase": float(rng.uniform(0, 6.28)),
           "blur": float(rng.uniform(0.0, 0.9)) if randomize else 0.0,
           "noise": float(rng.uniform(0.0, 0.03)) if randomize else 0.0,
           "defect": (float(rng.uniform(30, 60)), float(rng.uniform(10, 30)), 8.0) if defect else None}
    frames = _render(cx, cy, radius * px_per_m, H, W, rng, prm)
    labels = {"t": t, "x_m": X, "y_m": Y, "vx": VX, "vy": VY, "cx_px": cx, "cy_px": cy, "contact": contact,
              "bounces_s": bounces, "radius_m": radius, "restitution": e, "g": G}
    params = {"seed": seed, "zoom": zoom, "offset_px": off, **{k: v for k, v in prm.items()}}
    return Video(frames, dt, px_per_m, labels, params)


def dataset(n: int, *, seed: int = 0, **kw) -> list[Video]:
    return [bouncing_ball_scene(seed=seed + i, **kw) for i in range(n)]


# ============================================================================================ measuring a video
def track_object(frames) -> dict[str, np.ndarray]:
    """Centre ``(cx, cy)`` [px] and area [px] of the brightest-contrast object per frame (NaN when none is found)."""
    from scipy import ndimage
    F = np.asarray(frames, float)
    bg = np.median(F, axis=0)
    cx, cy, area = [], [], []
    for f in F:
        d = np.abs(f - bg)
        thr = max(0.5 * d.max(), 0.1)
        lab, n = ndimage.label(d > thr)
        if n == 0:
            cx.append(np.nan)
            cy.append(np.nan)
            area.append(0.0)
            continue
        sizes = ndimage.sum(np.ones_like(d), lab, range(1, n + 1))
        k = int(np.argmax(sizes)) + 1
        m = lab == k
        w = d * m
        yy, xx = np.nonzero(m)
        cx.append(float((w[yy, xx] * xx).sum() / w[yy, xx].sum()))
        cy.append(float((w[yy, xx] * yy).sum() / w[yy, xx].sum()))
        area.append(float(m.sum()))
    return {"cx": np.array(cx), "cy": np.array(cy), "area": np.array(area)}


def physics_checks(video, *, dt: float | None = None, px_per_m: float | None = None, g: float = G,
                   g_rtol: float = 0.10, area_rtol: float = 0.25, max_speed: float = 10.0) -> dict[str, Any]:
    """Physics checks of a ball video from its pixels; ``video`` is a :class:`Video` or frames (then give ``dt`` and
    ``px_per_m``). Returns ``{"checks": [...], "passed": bool, "track": ..., "g_fit": ...}``."""
    frames = video.frames if isinstance(video, Video) else np.asarray(video)
    dt = video.dt if isinstance(video, Video) and dt is None else dt
    ppm = video.px_per_m if isinstance(video, Video) and px_per_m is None else px_per_m
    tr = track_object(frames)
    y = -tr["cy"] / ppm                                    # metres, up
    x = tr["cx"] / ppm
    found = np.isfinite(y)
    checks = []
    checks.append({"name": "object visible in every frame", "value": float(found.mean()), "limit": 1.0,
                   "passed": bool(found.all())})
    a_med = np.nanmedian(tr["area"][found]) if found.any() else 0.0
    dev = float(np.nanmax(np.abs(tr["area"][found] - a_med)) / max(a_med, 1e-9)) if found.any() else np.inf
    checks.append({"name": "object area conserved (no growth, fading, vanishing)", "value": dev, "limit": area_rtol,
                   "passed": bool(found.all() and dev <= area_rtol)})
    # free-flight segments: split at the floor contacts (local minima of the height), drop the frame on each side of
    # a contact (the bounce happens between frames), fit y = -a t^2 / 2 + b t + c on each segment of >= 6 frames
    t = np.arange(len(frames)) * dt
    yy = np.where(found, y, np.nan)
    ok = np.isfinite(yy)
    mins = [i for i in range(1, len(yy) - 1) if ok[i - 1:i + 2].all() and yy[i] < yy[i - 1] and yy[i] <= yy[i + 1]]
    cuts = [-1] + mins + [len(yy)]
    fits, apex = [], []
    for lo, hi in zip(cuts[:-1], cuts[1:], strict=True):
        idx = np.arange(lo + 2, hi - 1)
        idx = idx[ok[idx]] if len(idx) else idx
        if len(idx) >= 6 and np.ptp(yy[idx]) > 3.0 / ppm:          # skip a ball resting or rolling on the floor
            c = np.polyfit(t[idx], yy[idx], 2)
            fits.append((float(-2 * c[0]), len(idx)))
            apex.append(float(np.max(np.polyval(c, np.linspace(t[idx[0]], t[idx[-1]], 200)))))
    g_fit = float(np.average([f[0] for f in fits], weights=[f[1] for f in fits])) if fits else float("nan")
    checks.append({"name": "free-flight acceleration = g (fitted between bounces)",
                   "value": abs(g_fit - g) / g if np.isfinite(g_fit) else float("inf"), "limit": g_rtol,
                   "passed": bool(np.isfinite(g_fit) and abs(g_fit - g) / g <= g_rtol),
                   "detail": f"g_fit = {g_fit:.2f} m/s2 over {len(fits)} flight segment(s)"})
    # no teleport: no frame-to-frame speed above what the fall height allows, sqrt(vx^2 + 2 g H) (30 % margin)
    v = np.hypot(np.diff(x), np.diff(yy)) / dt
    vmax = float(np.nanmax(v)) if np.isfinite(v).any() else float("inf")
    vx_med = float(np.nanmedian(np.abs(np.diff(x)) / dt)) if ok.sum() > 2 else 0.0
    h_top = float(np.nanmax(yy) - np.nanmin(yy)) if ok.any() else 0.0
    v_bound = min(1.3 * np.sqrt(vx_med ** 2 + 2 * g * h_top) + 2.0 / (ppm * dt), max_speed)
    checks.append({"name": "no teleport (speed within what the fall height allows)", "value": vmax,
                   "limit": float(v_bound), "passed": bool(vmax <= v_bound)})
    # energy per unit mass: the apex heights of successive flights must not increase
    floor = np.nanmin(yy) if ok.any() else 0.0
    apex = [h - floor for h in apex]
    rises = [b - a for a, b in zip(apex, apex[1:], strict=False)]
    worst = max(rises) / max(max(apex), 1e-9) if rises else 0.0
    checks.append({"name": "energy never increases across a bounce (apex heights)", "value": float(max(worst, 0.0)),
                   "limit": 0.05, "passed": bool(worst <= 0.05), "detail": f"apex heights {np.round(apex, 3).tolist()} m"})
    return {"checks": checks, "passed": all(c["passed"] for c in checks), "track": tr, "g_fit": g_fit}


def video_check(seed: int = 0, edit: str = "none") -> dict[str, Any]:
    """A synthetic bouncing-ball video (exact physics, randomized camera), optionally edited (``"time_warp"``,
    ``"teleport"``, ``"fade"``, ``"gravity_flip"``), judged by :func:`physics_checks` from its pixels alone."""
    v = bouncing_ball_scene(seed=seed)
    if edit != "none":
        v = corrupt(v, edit, seed=seed)
    r = physics_checks(v)
    return {"decision": "APPROVED" if r["passed"] else "REJECT", "edit": edit, "g_fit": r["g_fit"],
            "checks": [{k: c[k] for k in ("name", "passed", "value") if k in c} for c in r["checks"]]}


def corrupt(video: Video, kind: str, seed: int = 0) -> Video:
    """Non-physical edits: ``"time_warp"`` (motion played at a varying rate), ``"teleport"`` (frames swapped in the
    middle), ``"fade"`` (the object fades out), ``"gravity_flip"`` (the video played backwards in time after the
    first bounce, so the ball gains energy)."""
    F = video.frames.copy()
    n = len(F)
    if kind == "time_warp":
        s = np.linspace(0, 1, n) ** 1.8 * (n - 1)
        F = np.stack([F[int(round(i))] for i in s])
    elif kind == "teleport":
        k = n // 2
        F[k:k + 4] = F[k + 12:k + 16][: len(F[k:k + 4])]
    elif kind == "fade":
        bg = np.median(video.frames, axis=0)
        w = np.clip(1.0 - np.linspace(-0.5, 1.5, n), 0.0, 1.0)[:, None, None]
        F = bg[None] + (F - bg[None]) * w
    elif kind == "gravity_flip":
        F = F[::-1].copy()
    else:
        raise ValueError(f"unknown corruption {kind!r}")
    return Video(F.astype(np.float32), video.dt, video.px_per_m, dict(video.labels, corrupted=kind), video.params)


# ============================================================================================ world model
class WorldModel:
    """Encoder (conv) -> latent ``z`` -> GRU dynamics -> decoder (deconv); trained to predict frame t+1 from frames
    <= t. Small enough to train on a CPU in minutes on 64 x 96 frames."""

    def __init__(self, H: int = 64, W: int = 96, latent: int = 32, seed: int = 0):
        import torch
        import torch.nn as nn
        torch.manual_seed(seed)
        self.H, self.W, self.latent = H, W, latent

        class Net(nn.Module):
            def __init__(s):
                super().__init__()
                s.enc = nn.Sequential(nn.Conv2d(1, 16, 4, 2, 1), nn.SiLU(), nn.Conv2d(16, 32, 4, 2, 1), nn.SiLU(),
                                      nn.Conv2d(32, 64, 4, 2, 1), nn.SiLU(), nn.Flatten(),
                                      nn.Linear(64 * (H // 8) * (W // 8), latent))
                s.gru = nn.GRU(latent, 128, batch_first=True)
                s.head = nn.Linear(128, latent)
                s.dec_fc = nn.Linear(latent, 64 * (H // 8) * (W // 8))
                s.dec = nn.Sequential(nn.ConvTranspose2d(64, 32, 4, 2, 1), nn.SiLU(),
                                      nn.ConvTranspose2d(32, 16, 4, 2, 1), nn.SiLU(),
                                      nn.ConvTranspose2d(16, 1, 4, 2, 1))

            def encode(s, x):                      # (B, T, H, W) -> (B, T, latent)
                B, T = x.shape[:2]
                return s.enc(x.reshape(B * T, 1, H, W)).reshape(B, T, -1)

            def decode(s, z):                      # (B, T, latent) -> (B, T, H, W)
                B, T = z.shape[:2]
                h = s.dec_fc(z.reshape(B * T, -1)).reshape(B * T, 64, H // 8, W // 8)
                return torch.sigmoid(s.dec(h)).reshape(B, T, H, W)

            def forward(s, x):                     # predict frames 1..T-1 from 0..T-2
                z = s.encode(x)
                h, _ = s.gru(z[:, :-1])
                zn = z[:, :-1] + s.head(h)
                return s.decode(zn), s.decode(z), z

            def free_run(s, x, ctx):               # encode ctx frames, then roll the latent with no new frames
                z = s.encode(x[:, :ctx])
                h_seq, h = s.gru(z)
                zl = z[:, -1:] + s.head(h_seq[:, -1:])
                out = []
                for _ in range(x.shape[1] - ctx):
                    out.append(zl)
                    h_seq, h = s.gru(zl, h)
                    zl = zl + s.head(h_seq)
                return s.decode(torch.cat(out, 1))

        self.net = Net()
        self.history: list[dict[str, float]] = []

    def n_parameters(self) -> int:
        return int(sum(p.numel() for p in self.net.parameters()))

    def fit(self, videos, *, steps: int = 1500, batch: int = 8, window: int = 16, lr: float = 2e-3, seed: int = 0,
            log_every: int = 50, free_run: int = 0):
        """Adam with a cosine learning rate on random windows of ``window`` frames: next-frame loss + reconstruction,
        and with ``free_run = ctx > 0`` also the loss of the frames after ``ctx`` context frames predicted without new
        observations (the way :meth:`rollout` is used; reduces the drift of teacher-forced training)."""
        import time

        import torch
        X = torch.tensor(np.stack([v.frames for v in videos]), dtype=torch.float32)
        opt = torch.optim.Adam(self.net.parameters(), lr=lr)
        rng = np.random.default_rng(seed)
        t0 = time.perf_counter()
        for k in range(steps):
            idx = torch.from_numpy(rng.integers(0, len(X), min(batch, len(X))))
            s0 = int(rng.integers(0, X.shape[1] - window + 1))
            x = X[idx, s0:s0 + window]
            pred, recon, _ = self.net(x)
            loss_p = torch.mean((pred - x[:, 1:]) ** 2)
            loss_r = torch.mean((recon - x) ** 2)
            loss = loss_p + 0.5 * loss_r
            if free_run:
                loss_f = torch.mean((self.net.free_run(x, free_run) - x[:, free_run:]) ** 2)
                loss = loss + loss_f
            opt.zero_grad(set_to_none=True)
            loss.backward()
            opt.step()
            for g_ in opt.param_groups:
                g_["lr"] = lr * 0.5 * (1 + np.cos(np.pi * (k + 1) / steps))
            if k % log_every == 0 or k == steps - 1:
                self.history.append({"step": k, "loss_pred": float(loss_p.detach()), "loss_recon": float(loss_r.detach()),
                                     "wall_s": time.perf_counter() - t0})
        self.net.eval()
        return self

    def rollout(self, context: np.ndarray, steps: int) -> np.ndarray:
        """Frames after ``context (Tc, H, W)``: the model's own predictions fed back (``steps`` frames)."""
        import torch
        with torch.no_grad():
            x = torch.tensor(np.asarray(context, np.float32))[None]
            z = self.net.encode(x)
            h_seq, h = self.net.gru(z)
            zl = z[:, -1:] + self.net.head(h_seq[:, -1:])
            out = []
            for _ in range(steps):
                out.append(self.net.decode(zl)[0, 0].numpy())
                h_seq, h = self.net.gru(zl, h)
                zl = zl + self.net.head(h_seq)
        return np.asarray(out)


# ============================================================================================ state-space world model
class StateEncoder:
    """A small CNN that reads the object's centre (pixels) from a frame, trained on the exact labels of the synthetic
    videos (the labels are free because the frames come from a simulation)."""

    def __init__(self, H: int = 64, W: int = 96, seed: int = 0):
        import torch
        import torch.nn as nn
        torch.manual_seed(seed)
        self.H, self.W = H, W
        self.net = nn.Sequential(nn.Conv2d(1, 16, 5, 2, 2), nn.SiLU(), nn.Conv2d(16, 32, 3, 2, 1), nn.SiLU(),
                                 nn.Conv2d(32, 32, 3, 2, 1), nn.SiLU(), nn.Flatten(),
                                 nn.Linear(32 * (H // 8) * (W // 8), 64), nn.SiLU(), nn.Linear(64, 2))

    def fit(self, videos, *, steps: int = 1500, batch: int = 64, lr: float = 2e-3, seed: int = 0):
        return self.fit_points(np.concatenate([v.frames for v in videos]),
                               np.concatenate([np.c_[v.labels["cx_px"], v.labels["cy_px"]] for v in videos]),
                               steps=steps, batch=batch, lr=lr, seed=seed)

    def fit_points(self, frames, points_px, *, steps: int = 1500, batch: int = 64, lr: float = 2e-3, seed: int = 0):
        """Train on any images ``(N, H, W)`` with a labelled point ``(N, 2)`` (column, row in pixels)."""
        import torch
        X = torch.tensor(np.asarray(frames, np.float32)[:, None])
        Y = torch.tensor(np.asarray(points_px, float) / [self.W, self.H], dtype=torch.float32)
        opt = torch.optim.Adam(self.net.parameters(), lr=lr)
        rng = np.random.default_rng(seed)
        for k in range(steps):
            idx = torch.from_numpy(rng.integers(0, len(X), batch))
            loss = torch.mean((self.net(X[idx]) - Y[idx]) ** 2)
            opt.zero_grad(set_to_none=True)
            loss.backward()
            opt.step()
            for g_ in opt.param_groups:
                g_["lr"] = lr * 0.5 * (1 + np.cos(np.pi * (k + 1) / steps))
        self.net.eval()
        return self

    def predict(self, frames) -> np.ndarray:
        """``(T, 2)`` centre in pixels."""
        import torch
        with torch.no_grad():
            y = self.net(torch.tensor(np.asarray(frames, np.float32)[:, None])).numpy()
        return y * np.array([self.W, self.H])


def state_pairs(videos) -> tuple[np.ndarray, np.ndarray]:
    """``(s_t, s_t+1)`` with ``s = (x, y, vx, vy)`` in metres from the exact labels (the training data of a learned
    state dynamics)."""
    S, S1 = [], []
    for v in videos:
        s = np.c_[v.labels["x_m"], v.labels["y_m"], v.labels["vx"], v.labels["vy"]]
        S.append(s[:-1])
        S1.append(s[1:])
    return np.concatenate(S), np.concatenate(S1)


def render_like(video: Video, x_m, y_m) -> np.ndarray:
    """Frames of a trajectory ``(x_m, y_m)`` rendered with ``video``'s camera and appearance (its randomization
    parameters), noise from a fixed seed."""
    p = video.params
    H, W = video.frames.shape[1:]
    cx = np.asarray(x_m) * video.px_per_m + p["offset_px"][0]
    cy = H - 4 - np.asarray(y_m) * video.px_per_m + p["offset_px"][1]
    prm = {k: p[k] for k in ("bg", "fg", "gain", "texture", "tex_scale", "tex_phase", "blur", "noise", "defect")}
    return _render(cx, cy, video.labels["radius_m"] * video.px_per_m, H, W, np.random.default_rng(p["seed"] + 1), prm)


# ============================================================================================ Cosmos adapter
class CosmosAdapter:
    """``generate(prompt, frames=None, seed=0)`` on an NVIDIA Cosmos world foundation model NIM: ``POST {base}/infer``
    with ``prompt``, ``video`` (base64 MP4 of ``frames`` when given), ``seed``, ``video_params``; the answer's
    ``b64_video`` is decoded to frames (needs ``imageio`` with an FFmpeg plugin). Needs a Cosmos NIM (GPU) or a
    hosted endpoint and key; :class:`WorldModel` is the CPU path with the same role."""

    def __init__(self, base_url: str, api_key: str | None = None, timeout: float = 600.0):
        self.base, self.api_key, self.timeout = base_url.rstrip("/"), api_key, timeout

    @staticmethod
    def encode_mp4(frames, fps: float = 24.0) -> str:
        import io

        import imageio.v3 as iio
        buf = io.BytesIO()
        iio.imwrite(buf, (np.clip(np.asarray(frames), 0, 1) * 255).astype(np.uint8), extension=".mp4", fps=fps)
        return base64.b64encode(buf.getvalue()).decode()

    @staticmethod
    def decode_mp4(b64: str) -> np.ndarray:
        import imageio.v3 as iio
        arr = iio.imread(base64.b64decode(b64), extension=".mp4")
        arr = arr.astype(np.float32) / 255.0
        return arr.mean(-1) if arr.ndim == 4 else arr

    def request(self, prompt: str, frames=None, *, seed: int = 0, height: int = 704, width: int = 1280,
                frames_count: int = 121, fps: int = 24) -> dict[str, Any]:
        body: dict[str, Any] = {"prompt": prompt, "seed": int(seed),
                                "video_params": {"height": height, "width": width, "frames_count": frames_count,
                                                 "frames_per_sec": fps}}
        if frames is not None:
            body["video"] = self.encode_mp4(frames, fps)
        return body

    def generate(self, prompt: str, frames=None, **kw) -> np.ndarray:
        import urllib.request
        req = urllib.request.Request(self.base + "/infer", data=json.dumps(self.request(prompt, frames, **kw)).encode(),
                                     method="POST", headers={"Content-Type": "application/json",
                                                             "Accept": "application/json"})
        if self.api_key:
            req.add_header("Authorization", f"Bearer {self.api_key}")
        with urllib.request.urlopen(req, timeout=self.timeout) as r:
            out = json.loads(r.read())
        return self.decode_mp4(out["b64_video"])
