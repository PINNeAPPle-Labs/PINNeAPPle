"""PINNeAPPle World Model: physics-labelled synthetic video, a world model that trains on a CPU, and the physics
checks that decide whether any video (simulated, predicted or generated by a foundation model such as NVIDIA Cosmos)
is physically consistent.

``bouncing_ball_scene(...)``
    exact trajectory of a ball thrown under gravity and bouncing on the floor with restitution ``e`` (event-exact
    bounces), rendered as an image sequence with domain randomization (background colour and texture, lighting gain,
    camera offset and zoom, blur, sensor noise, an optional occluding defect). Labels per frame: centre in pixels and
    metres, velocity, contact events, pixels per metre, all randomization parameters.
``Video`` / ``dataset(n, ...)``
    a scene's frames ``(T, H, W)`` (grey, float in [0, 1]) with its labels; a list of randomized scenes.
``track_object(frames)``
    the object's centre and area per frame from the frames alone (background estimated from the frame median,
    intensity-weighted centroid of the largest connected blob).
``physics_checks(video or frames, dt, px_per_m)``
    what a physically consistent video of a thrown ball must satisfy, measured from the pixels: the fitted vertical
    acceleration between bounces equals g; the object's area is conserved (it does not appear, vanish or grow); no
    jump faster than the motion allows; mechanical energy never increases across a bounce (restitution <= 1). Returns
    check dicts (value, limit, passed) and the tracked trajectory.
``WorldModel``
    a small convolutional encoder -> latent -> recurrent latent dynamics -> decoder, trained on the frames (next-frame
    prediction) on a CPU; ``rollout(context, steps)`` generates future frames for the checks to judge.
``corrupt(video, kind)``
    non-physical edits (time warp, teleport, fade-out, gravity flip) to show the checks catch them.
``CosmosAdapter``
    the same ``generate(prompt, frames)`` interface on an NVIDIA Cosmos world foundation model NIM (``POST /v1/infer``
    with ``prompt``, ``video`` (base64 MP4), ``seed``, ``video_params``); returns ``b64_video``. Needs a Cosmos NIM on a
    GPU (or build.nvidia.com and a key); decoding MP4 needs ``imageio``.
"""
from __future__ import annotations

