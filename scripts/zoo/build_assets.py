def hub_only_entry(name: str, spec: dict, d: Path) -> dict:
    """Manifest entry of a Hub-only dataset from its generated files in ``d`` (``meta.json`` + ``<split>[-NN].npz``):
    SHA-256 and size of every file, row counts, and each column's dtype and per-row shape."""
    meta = json.loads((d / "meta.json").read_text())
    columns: dict = {}
    for fn in meta["files"]:
        with np.load(d / fn, allow_pickle=False) as z:
            for key in z.files:
                col = key.split("__", 1)[1]
                v = z[key]
                shape = "" if v.ndim == 1 else "[" + ", ".join(str(k) for k in v.shape[1:]) + "]"
                unit, desc = spec["columns"][col]
                columns.setdefault(col, {"unit": unit, "description": desc, "dtype": f"{v.dtype}{shape}"})
    missing = set(spec["columns"]) - set(columns)
    if missing:
        raise ValueError(f"{name}: documented columns not in the files: {sorted(missing)}")
    return {"version": spec["version"], "revision": f"v{spec['version']}", "hf_repo": hf_repo("d", name),
            "repo_type": "dataset",
            **{k: spec[k] for k in ("title", "description", "license", "source", "verification", "citation", "tags")},
            **({"split_rule": spec["split_rule"]} if "split_rule" in spec else {}),
            "splits": {s: {"n": int(meta["rows"][s]), "description": spec["splits"][s]} for s in meta["rows"]},
            "columns": columns,
            "files": {fn: {"sha256": art.sha256_file(d / fn), "size": (d / fn).stat().st_size}
                      for fn in meta["files"]}}


def build_hub_only(staging: Path) -> None:
    """(Re)write the manifest entries of the Hub-only datasets found in ``staging``; everything else is kept."""
    man = json.loads(art.MANIFEST.read_text())
    for name, spec in DATASETS.items():
        if spec.get("hub_only") and (staging / name / "meta.json").exists():
            new = hub_only_entry(name, spec, staging / name)
            man["datasets"][name] = _carry_versions(man["datasets"].get(name), new, spec)
            print(f"{name}: {len(new['files'])} files, {sum(f['size'] for f in new['files'].values()) / 1e6:.1f} MB")
    man["datasets"] = {n: man["datasets"][n] for n in DATASETS if n in man["datasets"]}
    art.MANIFEST.write_text(json.dumps(man, indent=1, sort_keys=False) + "\n")


def _carry_versions(old: dict | None, new: dict, spec: dict) -> dict:
    """``new`` with the release history: the previous entry moved under ``superseded`` when the version changed
    (its files lose ``bundled``: they now live only on the Hub, under the old tag)."""
    if not old:
        return new
    if old["version"] == new["version"] and old["revision"].startswith(new["revision"] + ".post"):
        new = {**new, "revision": old["revision"]}       # same files republished (new card, derived formats)
    history = list(old.get("superseded", []))
    if old["version"] != new["version"]:
        prev = {"version": old["version"], "revision": old["revision"], "superseded_by": new["version"],
                "superseded_reason": spec.get("supersedes_reason", ""),
                "files": {f: {k: v for k, v in fs.items() if k != "bundled"} for f, fs in old["files"].items()}}
        history = [prev] + history
    return {**new, "superseded": history} if history else new


def main(rover_dir: Path | None, only: list[str] | None = None, heatsink_natural_dir: Path | None = None,
         airfoil_gnn_dir: Path | None = None) -> None:
    from pinneapple_hub.zoo import _models

    old_man = json.loads(art.MANIFEST.read_text()) if art.MANIFEST.exists() else {"models": {}, "datasets": {}}
    keep = lambda kind, n: only is not None and n not in only and n in old_man[kind]  # noqa: E731
    print("datasets ...", flush=True)
    builders = {"airfoil_rans_cst_re4e6": build_airfoil_dataset,
                "heatsink_forced_convection": lambda: build_heatsink_dataset("forced"),
                "heatsink_natural_convection": lambda: build_heatsink_dataset("natural"),
                "rover_contact_grc1_viper": build_rover_dataset, "single_wheel_tests": build_single_wheel}
    built = {n: f() for n, f in builders.items() if not keep("datasets", n)}
    ds_man = {}
    for name, spec in DATASETS.items():
        if keep("datasets", name) or spec.get("hub_only"):            # Hub-only: entered with --hub-only
            if name in old_man["datasets"]:
                ds_man[name] = old_man["datasets"][name]
            continue
        splits = built[name]
        cols_spec = spec["columns"] or SW_UNITS
        all_cols = sorted({c for s in splits.values() for c in s})
        columns = {c: {"unit": cols_spec.get(c, ("-", ""))[0], "description": cols_spec.get(c, ("-", c))[1],
                       "dtype": str(next(s[c] for s in splits.values() if c in s).dtype)} for c in all_cols}
        missing = [c for c in all_cols if c not in cols_spec and c not in ("source_width_mm", "source_depth_mm")]
        if missing:
            raise ValueError(f"{name}: undocumented columns {missing}")
        for c in ("source_width_mm", "source_depth_mm"):
            if c in columns:
                columns[c].update(unit="mm", description=f"heat-source footprint {c.split('_')[1]} = "
                                                         f"source_frac_{c[7]} x base_{c.split('_')[1]}_mm")
        ds_man[name] = {"version": spec["version"], "revision": f"v{spec['version']}", "hf_repo": hf_repo("d", name),
                        "repo_type": "dataset",
                        **{k: spec[k] for k in ("title", "description", "license", "source", "verification",
                                                "citation", "tags")},
                        **({"split_rule": spec["split_rule"]} if "split_rule" in spec else {}),
                        "splits": {s: {"n": int(len(next(iter(v.values())))), "description": spec["splits"][s]}
                                   for s, v in splits.items()},
                        "columns": columns,
                        "files": {"data.npz": _file(ASSETS / "datasets" / name / "data.npz")}}
        if name == "rover_contact_grc1_viper":
            ds_man[name]["physics"] = rover_physics()
        ds_man[name] = _carry_versions(old_man["datasets"].get(name), ds_man[name], spec)
    write_manifest({k: v for k, v in old_man["models"].items() if only is not None}, ds_man)

    makers = {"airfoil_cst_rans_mlp": airfoil_model, "heatsink_forced_mlp": heatsink_model,
              "airfoil_cst_rans_gnn": lambda: airfoil_gnn_model(_need(airfoil_gnn_dir, "--airfoil-gnn")),
              "heatsink_natural_mlp": lambda: heatsink_natural_model(_need(heatsink_natural_dir, "--heatsink-natural")),
              "rover_contact_grc1_viper": lambda: rover_model(_need(rover_dir, "--rover"))}
    m_man = {}
    for name, spec in MODELS.items():
        if keep("models", name):
            m_man[name] = old_man["models"][name]
            continue
        print(f"model {name} ...", flush=True)
        state, cfg = makers[name]()
        d = ASSETS / "models" / name
        _save_weights(d / "weights.pt", state)
        (d / "config.json").write_text(json.dumps({**cfg, "adapter": spec["adapter"]}, indent=1) + "\n")
        card = ModelCard(name=name, description=spec["description"], task=spec["task"], version=spec["version"],
                         inputs=spec["inputs"], outputs=spec["outputs"], validity_range=spec["validity_range"],
                         known_limitations=spec["known_limitations"], architecture=spec["architecture"],
                         architecture_config=spec["architecture_config"], equations=spec["equations"],
                         training_config=spec["training_config"],
                         data_lineage={**spec["data_lineage"], **({"physics": cfg["physics"]} if "soil" in
                                                                  cfg.get("physics", {}) else {})},
                         reference_source=spec["reference_source"], citation=spec["citation"],
                         license=spec["license"], tags=spec["tags"], pinneapple_version=_version())
        mspec = {k: spec[k] for k in ("version", "adapter", "dataset", "task", "tags", "guard_metrics", "acceptance",
                                      "card_tolerance")}
        state_t = torch.load(d / "weights.pt", map_location="cpu", weights_only=True)
        model = _models.ADAPTERS[spec["adapter"]](name, card, {**cfg, "adapter": spec["adapter"]}, state_t, mspec)
        card.validation_metrics = model.evaluate_splits(model.eval_splits)
        from pinneapple_hub import zoo
        rep = zoo.validate(model)
        card.attach_trust_report(rep)
        print(f"  {rep.decisao}  " + ", ".join(f"{k}={v:.4g}" for k, v in card.validation_metrics.items()
                                               if not k.endswith("/n")))
        if rep.decisao != "APPROVED":
            raise SystemExit(f"{name} did not pass the gate:\n{rep.to_markdown()}")
        card.save(str(d / "model_card.json"))
        m_man[name] = {**mspec, "revision": f"v{spec['version']}", "hf_repo": hf_repo("m", name), "repo_type": "model",
                       "files": {f: _file(d / f) for f in ("weights.pt", "config.json", "model_card.json")}}
        m_man[name] = _carry_versions(old_man["models"].get(name), m_man[name], spec)
        write_manifest({**({k: v for k, v in old_man["models"].items() if only is not None}), **m_man}, ds_man)
    total = sum(f["size"] for k in ("models", "datasets") for e in art.manifest()[k].values()
                for f in e["files"].values() if f.get("bundled"))
    print(f"done: {len(m_man)} models, {len(ds_man)} datasets, {total / 1e6:.2f} MB bundled")


def _need(path: Path | None, flag: str) -> Path:
    if path is None:
        raise SystemExit(f"this build needs {flag} DIR (or --only without that item)")
    return path


