"""The official benchmark cases and their protocol (#30): the table, the page, and what a reproduction means.

The interesting property is not that a case trains -- it is that the published table is *the same table the protocol
produces*: the page is generated from the results file, the results file is regenerated by the runner, and a
reproduction is judged against a stated tolerance per metric. So the tests here check the declaration, the page and
the comparison, and run one case at a test budget instead of the published one.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pytest

from pinneapple_tools.benchmark_suite import cases

ROOT = Path(__file__).resolve().parent.parent


def test_three_cases_are_declared_with_distinct_ids_and_the_protocol_is_complete():
    assert len(cases.CASES) == 3
    assert len({c.id for c in cases.CASES}) == 3
    for case in cases.CASES:
        for field in cases.REQUIRED_CASE_FIELDS:
            assert case.as_dict()[field] not in (None, "", ()), f"{case.id}: {field}"
        assert case.split_at > 0 and case.split_coord in ("t",), "the split is in time: the extrapolation is in time"
    for field in cases.REQUIRED_PROTOCOL_FIELDS:
        assert field in cases.PROTOCOL, field
    assert len(cases.PROTOCOL["seeds"]) >= 2, "one seed has no spread"
    assert "relative_l2" in cases.PROTOCOL["metrics"]


def test_the_published_page_is_what_the_results_file_generates():
    results = json.loads((ROOT / cases.RESULTS).read_text(encoding="utf-8"))
    assert (ROOT / cases.PAGE).read_text(encoding="utf-8") == cases.page(results)


def test_the_gate_passes_on_the_repository():
    assert cases.check(ROOT) == []


def test_the_gate_catches_a_page_that_drifted_from_the_results(tmp_path):
    results = json.loads((ROOT / cases.RESULTS).read_text(encoding="utf-8"))
    cases.write(results, root=tmp_path)
    page = tmp_path / cases.PAGE
    page.write_text(page.read_text(encoding="utf-8").replace("heat_1d", "heat_first"), encoding="utf-8")
    problems = cases.check(tmp_path)
    assert any("not what the results file generates" in p for p in problems)


def test_a_reproduction_outside_the_tolerance_is_reported():
    results = json.loads((ROOT / cases.RESULTS).read_text(encoding="utf-8"))
    assert cases.reproduces(results, results) == [], "the same numbers reproduce by definition"
    tampered = json.loads(json.dumps(results))
    first = next(iter(tampered["cases"].values()))
    first["summary"]["in_domain"]["relative_l2"]["mean"] *= 3.0
    problems = cases.reproduces(results, tampered)
    assert any("in_domain relative_l2" in p and "drift" in p for p in problems)


def test_the_interval_says_how_much_the_points_matter():
    rng = np.random.default_rng(0)
    ref = rng.normal(size=500)
    err = 0.1 * ref + 0.05 * rng.normal(size=500)
    lo, hi = cases.bootstrap_ci(err, ref)
    assert 0 < lo < hi < 1
    point = float(np.linalg.norm(err) / np.linalg.norm(ref))
    assert lo < point < hi, "the interval has to contain the estimate it is an interval for"
    with pytest.raises(ValueError):
        cases.bootstrap_ci(err, ref[:-1])


def test_a_case_runs_and_scores_both_windows_at_a_test_budget():
    budget = {"epochs": 30, "n_collocation": 128, "hidden_dim": 16, "n_layers": 2}
    result = cases.run_case("01", seeds=(0,), budget=budget)
    assert result["case"]["id"] == "01" and result["budget"] == budget
    run = result["runs"][0]
    for where in ("in_domain", "extrapolation"):
        block = run["metrics"][where]
        lo, hi = block["relative_l2_ci"]
        assert lo <= block["relative_l2"] <= hi
        assert np.isfinite(block["rmse"]) and np.isfinite(block["max_abs"])
    assert run["metrics"]["in_domain"]["rmse"] > 0
    assert result["summary"]["wall_time_s"]["mean"] > 0
